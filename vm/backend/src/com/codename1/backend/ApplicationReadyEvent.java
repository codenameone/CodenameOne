package com.codename1.backend;

/// Sent to every `@EventListener` method that takes it once start-up is over:
/// the server is accepting and every runner has returned.
public final class ApplicationReadyEvent {
    private final Backend backend;

    /// The event for `backend`; the generated wiring sends it.
    /// @param backend the server that started
    public ApplicationReadyEvent(Backend backend) {
        this.backend = backend;
    }

    /// The server that started.
    public Backend getBackend() {
        return backend;
    }
}

package com.codename1.backend.graphql;

/// Names the object type of a value returned for an interface or union field.
///
/// Without one, the engine uses a map's `__typename` entry, or else the simple
/// name of the value's class when the schema defines an object type by that
/// name -- Spring for GraphQL's default, `ClassNameTypeResolver`.
public interface TypeResolver {
    /// The name of an object type the abstract type includes, or null to fall
    /// back to the default.
    String resolveType(Object value);
}

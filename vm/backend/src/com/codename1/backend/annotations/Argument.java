package com.codename1.backend.annotations;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/// Binds one argument of a GraphQL field to this parameter of a
/// [SchemaMapping] method, converted to the parameter's type. An argument the
/// query leaves out, with no default, is null; a primitive parameter for one
/// is a build error unless the argument is non-null in the schema.
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.PARAMETER)
public @interface Argument {
    /// The argument's name in the schema. Required: a Java parameter name does
    /// not survive compilation.
    String value() default "";
    /// The argument's name; the same as [#value()].
    String name() default "";
}

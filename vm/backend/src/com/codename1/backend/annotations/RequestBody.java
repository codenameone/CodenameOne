package com.codename1.backend.annotations;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/// Binds the decoded request body to this parameter.
///
/// The body is decoded to the parameter's declared type using the generated
/// codec for it, so a controller receives its own type rather than a Map.
@Retention(RetentionPolicy.CLASS)
@Target(ElementType.PARAMETER)
public @interface RequestBody {
    /// Whether a request with no body is rejected.
    boolean required() default true;
}

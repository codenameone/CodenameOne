package com.codename1.backend.security.oauth2.server.authorization;

/// The clients an authorization server knows.
public interface RegisteredClientRepository {
    /// Stores `registeredClient`, in place of the one with its id if there is
    /// one.
    void save(RegisteredClient registeredClient);

    /// The client stored under this id, or null.
    RegisteredClient findById(String id);

    /// The client that calls itself this, or null.
    RegisteredClient findByClientId(String clientId);
}

package com.codename1.backend.security;

/// What the security layer knows about the thread's current request: who it is
/// from. Held by [SecurityContextHolder].
public interface SecurityContext {
    /// The authenticated principal, an anonymous token, or null when no chain
    /// has looked at the request.
    Authentication getAuthentication();

    /// Changes who the request is from. Signing a user in by hand also needs the
    /// chain's [SecurityContextRepository] to save it, or the next request starts
    /// anonymous again.
    void setAuthentication(Authentication authentication);
}

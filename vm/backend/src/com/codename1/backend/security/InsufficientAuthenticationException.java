package com.codename1.backend.security;

/// The request is anonymous, or not authenticated strongly enough, for what it
/// asked for. The chain raises it when an anonymous request is denied, which is
/// what sends the client to sign in rather than answering 403.
public class InsufficientAuthenticationException extends AuthenticationException {
    public InsufficientAuthenticationException(String message) {
        super(message);
    }

    public InsufficientAuthenticationException(String message, Throwable cause) {
        super(message, cause);
    }
}

package com.codename1.backend.security.apikey;

/// Where API keys are kept. An application declares a bean of this type, and
/// `http.apiKey(...)` looks presented keys up in it.
public interface ApiKeyRepository {
    /// The key with this hash, or null. A revoked key is returned like any
    /// other; refusing it is the caller's.
    ///
    /// @param hash the lowercase hexadecimal SHA-256 of a presented key
    ApiKey findByHash(String hash);
}

package com.codename1.impl.backend.test;

/// What a test wiring adds to an application's: its beans by name, so a test's
/// `@Autowired` fields can be filled. Only generated test wirings implement it --
/// the production wiring has no lookup of any kind.
public interface TestBeans {
    /// The bean of this name -- the instance, or for a scoped or lazy bean its
    /// stand-in -- or null when its condition left it out.
    Object bean(String name);
}

package com.codename1.impl.html5;

import com.codename1.impl.CodenameOneImplementation;
import com.codename1.security.CryptoEngine;
import com.codename1.security.Hash;
import com.codename1.security.PortCryptoEngine;

/// The browser's [CryptoEngine]: large signature and hash batches run on the GPU through WebGPU,
/// with the same kernels the native ports run on Metal and Vulkan (`js/cn1_crypto_gpu.js`,
/// generated by `scripts/crypto-gpu/gen.py` and loaded the first time a batch asks for it).
///
/// The CPU still does everything a verification does before its scalar multiplications --
/// parsing, decompression, the challenge hash, the inverse -- through
/// [CryptoEngine#gpuRecord], and the GPU's answer for a record is the single verify's answer.
/// Where the browser has no WebGPU adapter, or a batch is small, nothing here runs and the batch
/// takes the portable Java path. WebGPU answers asynchronously: the natives suspend only the
/// thread that called them, so the asynchronous forms of [com.codename1.security.CryptoBatch]
/// leave the EDT free while the GPU works.
public class HTML5CryptoEngine extends PortCryptoEngine {
    // below these a batch is faster on the CPU than its round trip to the GPU
    private static final int MIN_GPU_VERIFY = 256;
    private static final long MIN_GPU_HASH_BYTES = 1L << 20;

    // the most entries one dispatch takes: WebGPU guarantees 65535 workgroups of 64, and a
    // storage binding of 128MB, which a slice of ECDSA records (196 bytes each) stays under
    private static final int MAX_PER_DISPATCH = 1 << 19;
    private static final long MAX_HASH_BYTES_PER_DISPATCH = 1L << 26;

    // kernel numbers, as port.js names them
    private static final int K_ECDSA = 0;
    private static final int K_SCHNORR = 1;
    private static final int K_ED25519 = 2;
    private static final int K_SHA256 = 3;
    private static final int K_KECCAK256 = 4;

    /// Creates the engine over the browser port.
    ///
    /// #### Parameters
    ///
    /// - `impl`: the port, whose native derivation PBKDF2 uses
    public HTML5CryptoEngine(CodenameOneImplementation impl) {
        super(impl);
    }

    // asked on every batch rather than remembered: port.js keeps the answer while its device lives
    // and asks for a new one after a device loss, which a cached answer here would never see
    private static boolean gpu() {
        return gpuOpen();
    }

    @Override
    public void verifyPacked(int algorithm, byte[] messages, int messageLength, byte[] signatures, byte[] keys,
            int keyLength, byte[] results, int count) {
        if (count < MIN_GPU_VERIFY || !gpu()) {
            return;
        }
        for (int at = 0; at < count; at += MAX_PER_DISPATCH) {
            int n = Math.min(MAX_PER_DISPATCH, count - at);
            verifyOnGpu(algorithm, messages, messageLength, signatures, keys, keyLength, results, at, n, null);
        }
    }

    @Override
    public void verifyBatch(int algorithm, byte[][] messages, byte[][] signatures, byte[][] publicKeys,
            byte[] results) {
        if (results.length < MIN_GPU_VERIFY || !gpu()) {
            return;
        }
        Object[] arrays = {messages, signatures, publicKeys};
        for (int at = 0; at < results.length; at += MAX_PER_DISPATCH) {
            int n = Math.min(MAX_PER_DISPATCH, results.length - at);
            verifyOnGpu(algorithm, null, 0, null, null, 0, results, at, n, arrays);
        }
    }

    // entries at..at+n of a packed batch, or of an array batch when arrays is given; entries
    // left at 2 when the GPU fails are verified in Java by the caller
    private void verifyOnGpu(int algorithm, byte[] messages, int messageLength, byte[] signatures, byte[] keys,
            int keyLength, byte[] results, int at, int n, Object[] arrays) {
        int words = gpuRecordWords(algorithm);
        int[] records = new int[n * words];
        int[] index = new int[n];
        int pending = 0;
        for (int i = at; i < at + n; i++) {
            if (results[i] != 2) {
                continue;
            }
            int prep;
            if (arrays == null) {
                prep = gpuRecord(algorithm, messages, messageLength * i, messageLength, signatures, 64 * i, keys,
                        keyLength * i, keyLength, records, pending * words);
            } else {
                byte[] m = ((byte[][]) arrays[0])[i];
                byte[] k = ((byte[][]) arrays[2])[i];
                prep = gpuRecord(algorithm, m, 0, m.length, ((byte[][]) arrays[1])[i], 0, k, 0, k.length, records,
                        pending * words);
            }
            if (prep == 2) {
                index[pending++] = i;
            } else {
                results[i] = (byte) prep;
            }
        }
        if (pending == 0) {
            return;
        }
        int kernel = algorithm == BATCH_SECP256K1 ? K_ECDSA : algorithm == BATCH_SCHNORR ? K_SCHNORR : K_ED25519;
        int[] answers = new int[pending];
        if (!gpuVerify(kernel, records, words, pending, answers)) {
            return;
        }
        for (int j = 0; j < pending; j++) {
            results[index[j]] = answers[j] != 0 ? (byte) 1 : 0;
        }
    }

    @Override
    public boolean hashPacked(String algorithm, byte[] inputs, int inputLength, int count, byte[] digests) {
        // an input past one dispatch's budget cannot be split across dispatches; the CPU takes it
        if ((long) inputLength * count < MIN_GPU_HASH_BYTES || inputLength > MAX_HASH_BYTES_PER_DISPATCH
                || !gpu()) {
            return false;
        }
        int kernel = Hash.SHA256.equals(algorithm) ? K_SHA256 : K_KECCAK256;
        int step = (int) Math.max(1, Math.min(MAX_PER_DISPATCH, MAX_HASH_BYTES_PER_DISPATCH / Math.max(1, inputLength)));
        for (int at = 0; at < count; at += step) {
            int n = Math.min(step, count - at);
            if (!gpuHash(kernel, inputs, inputLength * at, inputLength, n, digests, 32 * at)) {
                return at == 0 ? false : hashRestInJava(kernel, inputs, inputLength, at, count, digests);
            }
        }
        return true;
    }

    // a GPU that failed part way through: the entries it did not reach, on the CPU
    private static boolean hashRestInJava(int kernel, byte[] inputs, int inputLength, int from, int count,
            byte[] digests) {
        byte[] one = new byte[inputLength];
        for (int i = from; i < count; i++) {
            System.arraycopy(inputs, inputLength * i, one, 0, inputLength);
            byte[] d = kernel == K_SHA256 ? Hash.sha256(one) : Hash.keccak256(one);
            System.arraycopy(d, 0, digests, 32 * i, 32);
        }
        return true;
    }

    // whether the browser has a WebGPU device; port.js opens it once and again after a loss
    private static native boolean gpuOpen();

    // runs count records of words each through a verify kernel, an answer per record
    private static native boolean gpuVerify(int kernel, int[] records, int words, int count, int[] answers);

    // hashes count inputs of length bytes from offset, the digests written from digestOffset
    private static native boolean gpuHash(int kernel, byte[] inputs, int offset, int length, int count,
            byte[] digests, int digestOffset);
}

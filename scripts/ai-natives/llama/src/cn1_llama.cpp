#include "cn1_llama.h"
#include "llama.h"

#include <cmath>
#include <cstring>
#include <mutex>
#include <string>
#include <vector>

namespace {

struct Session {
    llama_model *model = nullptr;
    llama_context *ctx = nullptr;
    const llama_vocab *vocab = nullptr;
    llama_sampler *sampler = nullptr;
    std::string error;
    std::string pending;   // generated bytes not yet returned
    std::string piece;     // what the last cn1llama_next returned
    std::vector<float> embedding;
    int prompt_tokens = 0;
    int completion_tokens = 0;
    int max_tokens = 0;
    bool done = true;
    llama_token last = 0;
};

const int MAX_SESSIONS = 16;
Session *sessions[MAX_SESSIONS + 1];
std::mutex table_lock;
std::string open_error;
std::once_flag backend_once;

Session *get(int h) {
    std::lock_guard<std::mutex> g(table_lock);
    return h > 0 && h <= MAX_SESSIONS ? sessions[h] : nullptr;
}

/* Length of the longest prefix of s that ends on a UTF-8 character boundary. */
size_t complete_utf8(const std::string &s) {
    size_t n = s.size();
    size_t i = n;
    int back = 0;
    while (i > 0 && back < 4) {
        unsigned char c = (unsigned char) s[i - 1];
        if ((c & 0xC0) != 0x80) {
            size_t need = c < 0x80 ? 1 : (c >> 5) == 0x6 ? 2 : (c >> 4) == 0xE ? 3
                    : (c >> 3) == 0x1E ? 4 : 1;
            return (n - (i - 1)) >= need ? n : i - 1;
        }
        i--;
        back++;
    }
    return n;
}

bool decode_all(Session *s, const std::vector<llama_token> &tokens) {
    int batch = (int) llama_n_batch(s->ctx);
    for (size_t at = 0; at < tokens.size(); at += batch) {
        int n = (int) std::min((size_t) batch, tokens.size() - at);
        if (llama_decode(s->ctx, llama_batch_get_one(
                const_cast<llama_token *>(tokens.data()) + at, n)) != 0) {
            return false;
        }
    }
    return true;
}

bool tokenize(Session *s, const std::string &text, bool add_special,
              std::vector<llama_token> &out) {
    int n = -llama_tokenize(s->vocab, text.c_str(), (int32_t) text.size(), nullptr, 0,
                            add_special, true);
    if (n <= 0) {
        out.clear();
        return n == 0;
    }
    out.resize(n);
    return llama_tokenize(s->vocab, text.c_str(), (int32_t) text.size(), out.data(), n,
                          add_special, true) == n;
}

}  // namespace

extern "C" int cn1llama_open(const char *path, int n_ctx, int n_gpu_layers, int n_threads) {
    std::call_once(backend_once, [] { llama_backend_init(); });
    llama_model_params mp = llama_model_default_params();
    mp.n_gpu_layers = n_gpu_layers < 0 ? 999 : n_gpu_layers;
    llama_model *model = llama_model_load_from_file(path, mp);
    if (!model) {
        std::lock_guard<std::mutex> g(table_lock);
        open_error = std::string("Not a loadable GGUF model: ") + path;
        return 0;
    }
    llama_context_params cp = llama_context_default_params();
    if (n_ctx > 0) {
        cp.n_ctx = (uint32_t) n_ctx;
    }
    if (n_threads > 0) {
        cp.n_threads = n_threads;
        cp.n_threads_batch = n_threads;
    }
    llama_context *ctx = llama_init_from_model(model, cp);
    if (!ctx) {
        llama_model_free(model);
        std::lock_guard<std::mutex> g(table_lock);
        open_error = "Could not create a context; try a smaller context size";
        return 0;
    }
    Session *s = new Session();
    s->model = model;
    s->ctx = ctx;
    s->vocab = llama_model_get_vocab(model);
    std::lock_guard<std::mutex> g(table_lock);
    for (int h = 1; h <= MAX_SESSIONS; h++) {
        if (!sessions[h]) {
            sessions[h] = s;
            return h;
        }
    }
    open_error = "Too many models open";
    llama_free(ctx);
    llama_model_free(model);
    delete s;
    return 0;
}

extern "C" const char *cn1llama_last_error(int handle) {
    if (handle == 0) {
        std::lock_guard<std::mutex> g(table_lock);
        return open_error.empty() ? nullptr : open_error.c_str();
    }
    Session *s = get(handle);
    return s && !s->error.empty() ? s->error.c_str() : nullptr;
}

extern "C" int cn1llama_start(int handle, int n_messages, const char **roles,
                              const char **contents, int max_tokens, float temperature,
                              float top_p, int seed, const char *grammar) {
    Session *s = get(handle);
    if (!s) {
        return 0;
    }
    s->error.clear();
    s->pending.clear();
    s->done = true;
    s->prompt_tokens = 0;
    s->completion_tokens = 0;
    s->max_tokens = max_tokens;

    std::vector<llama_chat_message> msgs((size_t) n_messages);
    for (int i = 0; i < n_messages; i++) {
        msgs[i].role = roles[i];
        msgs[i].content = contents[i];
    }
    const char *tmpl = llama_model_chat_template(s->model, nullptr);
    std::vector<char> buf(4096);
    int len = llama_chat_apply_template(tmpl, msgs.data(), msgs.size(), true,
                                        buf.data(), (int32_t) buf.size());
    if (len > (int) buf.size()) {
        buf.resize((size_t) len);
        len = llama_chat_apply_template(tmpl, msgs.data(), msgs.size(), true,
                                        buf.data(), (int32_t) buf.size());
    }
    if (len < 0) {
        s->error = "The model has no chat template this llama.cpp understands";
        return 0;
    }
    std::vector<llama_token> tokens;
    if (!tokenize(s, std::string(buf.data(), (size_t) len), true, tokens) || tokens.empty()) {
        s->error = "Could not tokenize the prompt";
        return 0;
    }
    if (tokens.size() + 1 > llama_n_ctx(s->ctx)) {
        s->error = "The prompt is longer than the context window";
        return 0;
    }
    llama_memory_clear(llama_get_memory(s->ctx), true);
    if (!decode_all(s, tokens)) {
        s->error = "Could not evaluate the prompt";
        return 0;
    }
    s->prompt_tokens = (int) tokens.size();

    if (s->sampler) {
        llama_sampler_free(s->sampler);
    }
    s->sampler = llama_sampler_chain_init(llama_sampler_chain_default_params());
    if (grammar && *grammar) {
        llama_sampler *g = llama_sampler_init_grammar(s->vocab, grammar, "root");
        if (!g) {
            s->error = "Invalid grammar";
            return 0;
        }
        llama_sampler_chain_add(s->sampler, g);
    }
    if (temperature <= 0.0f) {
        llama_sampler_chain_add(s->sampler, llama_sampler_init_greedy());
    } else {
        llama_sampler_chain_add(s->sampler, llama_sampler_init_top_p(top_p, 1));
        llama_sampler_chain_add(s->sampler, llama_sampler_init_temp(temperature));
        llama_sampler_chain_add(s->sampler, llama_sampler_init_dist(
                seed < 0 ? LLAMA_DEFAULT_SEED : (uint32_t) seed));
    }
    s->done = false;
    return 1;
}

extern "C" int cn1llama_next(int handle, const char **out) {
    Session *s = get(handle);
    if (!s) {
        return 0;
    }
    while (!s->done) {
        if (s->completion_tokens >= s->max_tokens
                || (uint32_t) (s->prompt_tokens + s->completion_tokens) >= llama_n_ctx(s->ctx)) {
            s->done = true;
            break;
        }
        llama_token tok = llama_sampler_sample(s->sampler, s->ctx, -1);
        if (llama_vocab_is_eog(s->vocab, tok)) {
            s->done = true;
            break;
        }
        s->completion_tokens++;
        char buf[256];
        int n = llama_token_to_piece(s->vocab, tok, buf, sizeof(buf), 0, false);
        if (n > 0) {
            s->pending.append(buf, (size_t) n);
        }
        s->last = tok;
        if (llama_decode(s->ctx, llama_batch_get_one(&s->last, 1)) != 0) {
            s->error = "Decoding failed";
            s->done = true;
        }
        size_t ready = complete_utf8(s->pending);
        if (ready > 0) {
            s->piece = s->pending.substr(0, ready);
            s->pending.erase(0, ready);
            *out = s->piece.c_str();
            return 1;
        }
    }
    if (!s->pending.empty()) {
        // An incomplete sequence at the very end is dropped rather than
        // handed to a UTF-8 decoder that would reject it.
        s->pending.clear();
    }
    return 0;
}

extern "C" int cn1llama_prompt_tokens(int handle) {
    Session *s = get(handle);
    return s ? s->prompt_tokens : 0;
}

extern "C" int cn1llama_completion_tokens(int handle) {
    Session *s = get(handle);
    return s ? s->completion_tokens : 0;
}

extern "C" int cn1llama_embed(int handle, const char *text, const float **out) {
    Session *s = get(handle);
    if (!s) {
        return 0;
    }
    s->error.clear();
    std::vector<llama_token> tokens;
    if (!tokenize(s, text, true, tokens) || tokens.empty()) {
        s->error = "Could not tokenize the input";
        return 0;
    }
    if (tokens.size() > llama_n_batch(s->ctx) || tokens.size() > llama_n_ctx(s->ctx)) {
        s->error = "The input is longer than the batch size";
        return 0;
    }
    int dim = llama_model_n_embd(s->model);
    llama_memory_clear(llama_get_memory(s->ctx), true);
    llama_set_embeddings(s->ctx, true);
    llama_batch batch = llama_batch_init((int32_t) tokens.size(), 0, 1);
    for (size_t i = 0; i < tokens.size(); i++) {
        batch.token[i] = tokens[i];
        batch.pos[i] = (llama_pos) i;
        batch.n_seq_id[i] = 1;
        batch.seq_id[i][0] = 0;
        batch.logits[i] = 1;
    }
    batch.n_tokens = (int32_t) tokens.size();
    int rc = llama_decode(s->ctx, batch);
    s->embedding.assign((size_t) dim, 0.0f);
    bool ok = rc == 0;
    if (ok) {
        const float *pooled = llama_pooling_type(s->ctx) != LLAMA_POOLING_TYPE_NONE
                ? llama_get_embeddings_seq(s->ctx, 0) : nullptr;
        if (pooled) {
            std::memcpy(s->embedding.data(), pooled, sizeof(float) * (size_t) dim);
        } else {
            for (size_t i = 0; i < tokens.size(); i++) {
                const float *e = llama_get_embeddings_ith(s->ctx, (int32_t) i);
                if (!e) {
                    ok = false;
                    break;
                }
                for (int d = 0; d < dim; d++) {
                    s->embedding[(size_t) d] += e[d] / (float) tokens.size();
                }
            }
        }
    }
    llama_batch_free(batch);
    llama_set_embeddings(s->ctx, false);
    llama_memory_clear(llama_get_memory(s->ctx), true);
    if (!ok) {
        s->error = "Could not compute the embedding";
        return 0;
    }
    double norm = 0;
    for (int d = 0; d < dim; d++) {
        norm += (double) s->embedding[(size_t) d] * s->embedding[(size_t) d];
    }
    norm = std::sqrt(norm);
    if (norm > 0) {
        for (int d = 0; d < dim; d++) {
            s->embedding[(size_t) d] = (float) (s->embedding[(size_t) d] / norm);
        }
    }
    *out = s->embedding.data();
    return dim;
}

extern "C" void cn1llama_close(int handle) {
    Session *s = nullptr;
    {
        std::lock_guard<std::mutex> g(table_lock);
        if (handle > 0 && handle <= MAX_SESSIONS) {
            s = sessions[handle];
            sessions[handle] = nullptr;
        }
    }
    if (!s) {
        return;
    }
    if (s->sampler) {
        llama_sampler_free(s->sampler);
    }
    llama_free(s->ctx);
    llama_model_free(s->model);
    delete s;
}

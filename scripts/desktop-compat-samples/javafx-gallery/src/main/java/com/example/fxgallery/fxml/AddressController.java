package com.example.fxgallery.fxml;

import java.net.URL;
import java.util.ResourceBundle;

import javafx.fxml.FXML;
import javafx.fxml.Initializable;
import javafx.scene.control.TextField;

/**
 * The controller of {@code address.fxml}, which {@code profile.fxml} includes.
 */
public class AddressController implements Initializable {

    @FXML
    private TextField streetField;
    @FXML
    private TextField cityField;

    @Override
    public void initialize(URL location, ResourceBundle resources) {
        cityField.setText(resources.getString("address.defaultCity"));
    }

    public String getCity() {
        return cityField.getText();
    }

    public void clear() {
        streetField.clear();
        cityField.clear();
    }
}

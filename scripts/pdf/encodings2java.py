"""Generates CodenameOne/src/com/codename1/impl/pdf/PdfEncodings.java.

Usage: encodings2java.py <dir holding PDFBox's resources> <out.java> <header.txt>

StandardEncoding, Symbol and ZapfDingbats come from the code columns of
Adobe's AFM files (Times-Roman's codes are StandardEncoding); WinAnsi and
MacRoman from Python's cp1252 and mac_roman codecs. Glyph names map to
Unicode through the Adobe Glyph List and its ZapfDingbats supplement.
"""
import os, sys
src, out, header = sys.argv[1:4]
afm = os.path.join(src, 'org/apache/pdfbox/resources/afm')
gld = os.path.join(src, 'org/apache/pdfbox/resources/glyphlist')

def glyphlist(name):
    m = {}
    for line in open(os.path.join(gld, name)):
        if line.startswith('#') or ';' not in line:
            continue
        n, c = line.strip().split(';')
        cs = c.split(' ')
        if len(cs) == 1:
            m.setdefault(n, int(cs[0], 16))
    return m

gl = glyphlist('glyphlist.txt')
zd = glyphlist('zapfdingbats.txt')

def afm_codes(font):
    names = [None] * 256
    for line in open(os.path.join(afm, font + '.afm'), encoding='latin-1'):
        if line.startswith('C '):
            parts = dict(p.strip().split(' ', 1) for p in line.split(';') if ' ' in p.strip())
            code = int(parts['C'])
            if 0 <= code < 256:
                names[code] = parts['N'].strip()
    return names

std = afm_codes('Times-Roman')
known = set(n for n in std if n)
rev = {}
for n, u in gl.items():
    rev.setdefault(u, []).append(n)

def by_codec(codec):
    names = [None] * 256
    for code in range(32, 256):
        try:
            u = ord(bytes([code]).decode(codec))
        except UnicodeDecodeError:
            continue
        cands = rev.get(u, [])
        pick = None
        for c in cands:
            if c in known:
                pick = c
                break
        if pick is None and cands:
            pick = sorted(cands, key=len)[0]
        names[code] = pick
    return names

win = by_codec('cp1252')
win[0xA0] = 'space'
win[0xAD] = 'hyphen'
mac = by_codec('mac_roman')
sym = afm_codes('Symbol')
zap = afm_codes('ZapfDingbats')
encs = [('STANDARD', std), ('WIN_ANSI', win), ('MAC_ROMAN', mac), ('SYMBOL', sym), ('ZAPF_DINGBATS', zap)]
used = set()
for _, e in encs:
    used.update(n for n in e if n)
unicode_of = {}
for n in sorted(used):
    u = gl.get(n, zd.get(n))
    if u is not None:
        unicode_of[n] = u

L = [open(header).read().rstrip(), 'package com.codename1.impl.pdf;', '',
     '/// The simple-font encodings a PDF can name and the Unicode value of',
     '/// every glyph name they use. Generated by `scripts/pdf/encodings2java.py`',
     '/// from the code columns of Adobe\'s AFM files and the Adobe Glyph List;',
     '/// do not edit by hand.',
     '@com.codename1.impl.SharedWithBackend',
     'public final class PdfEncodings {']
for name, e in encs:
    L.append('    /// Glyph names of %s by code, space separated, `.` where undefined.' % name)
    L.append('    private static final String %s =' % name)
    vals = [n if n else '.' for n in e]
    chunk = []
    lines = []
    cur = ''
    for v in vals:
        if len(cur) + len(v) + 1 > 70:
            lines.append(cur)
            cur = ''
        cur += v + ' '
    lines.append(cur)
    L.append('\n'.join('            "%s"%s' % (l, ' +' if i < len(lines) - 1 else ';') for i, l in enumerate(lines)))
    L.append('')
L.append('    /// Glyph name and Unicode value pairs, `name:hex` space separated.')
L.append('    private static final String UNICODE =')
items = ['%s:%x' % (n, u) for n, u in sorted(unicode_of.items())]
lines = []
cur = ''
for v in items:
    if len(cur) + len(v) + 1 > 70:
        lines.append(cur)
        cur = ''
    cur += v + ' '
lines.append(cur)
L.append('\n'.join('            "%s"%s' % (l, ' +' if i < len(lines) - 1 else ';') for i, l in enumerate(lines)))
L.append('')
L.append('    private PdfEncodings() {')
L.append('    }')
L.append('')
L.append('    /// The code table of built-in encoding `slot`: 0 standard, 1 WinAnsi,')
L.append('    /// 2 MacRoman, 3 Symbol, 4 ZapfDingbats. Kept behind a method so the')
L.append('    /// long tables are not copied into every class that reads them.')
L.append('    static String table(int slot) {')
L.append('        return slot == 1 ? WIN_ANSI : slot == 2 ? MAC_ROMAN : slot == 3 ? SYMBOL : slot == 4 ? ZAPF_DINGBATS')
L.append('                : STANDARD;')
L.append('    }')
L.append('')
L.append('    /// The glyph name to Unicode table.')
L.append('    static String unicode() {')
L.append('        return UNICODE;')
L.append('    }')
L.append('}')
open(out, 'w').write('\n'.join(L) + '\n')

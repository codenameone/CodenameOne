// The Compose Multiplatform build of the same commonMain the Codename One
// project compiles. Release builds only: the benchmark measures what ships.
import org.jetbrains.kotlin.gradle.plugin.mpp.NativeBuildType

plugins {
    kotlin("multiplatform")
    id("org.jetbrains.kotlin.plugin.compose")
    id("org.jetbrains.compose")
}

kotlin {
    jvm("desktop")
    listOf(iosSimulatorArm64(), iosArm64()).forEach { target ->
        target.binaries.executable(listOf(NativeBuildType.RELEASE)) {
            entryPoint = "keynote.ios.main"
        }
    }
    // The shared code is unchanged from the Codename One side, which needs no
    // opt-in for the material3 top bar.
    compilerOptions {
        optIn.add("androidx.compose.material3.ExperimentalMaterial3Api")
    }
    sourceSets {
        commonMain.dependencies {
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.material3)
            implementation(compose.materialIconsExtended)
            implementation("org.jetbrains.kotlinx:kotlinx-coroutines-core:1.10.2")
        }
        val desktopMain by getting {
            dependencies {
                implementation(compose.desktop.currentOs)
                implementation("org.jetbrains.kotlinx:kotlinx-coroutines-swing:1.10.2")
            }
        }
    }
}

compose.desktop {
    application {
        mainClass = "keynote.desktop.MainKt"
    }
}

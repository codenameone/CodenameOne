#!/usr/bin/env python3
"""Builds vm/ByteCodeTranslator/src/cn1_crypto_kernels_amalgamation.h.

The native crypto kernels ParparVM compiles into an application that uses
Codename One's blockchain cryptography are third-party C, vendored as ONE
generated header the way SQLite is (cn1_sqlite3_amalgamation.h): the
translator copies a single resource, and every target compiles it as part of
cn1_crypto_kernels.c.

  - libsecp256k1 (MIT), Bitcoin Core's secp256k1 library, with the recovery,
    extrakeys and schnorrsig modules
  - ed25519-donna (public domain), Andrew Moon's Ed25519

Usage:
  scripts/crypto-kernels/amalgamate.py <secp256k1 checkout> <ed25519-donna checkout>

Every #include "..." is replaced by the file's text, every time it appears;
the upstream headers carry include guards, so a repeated one compiles to
nothing, and nothing depends on which branch of an #if included it first.
System headers (<...>) are left alone. The pinned commits are recorded in the
output and in cn1_crypto_kernels_README.md.
"""
import os
import re
import subprocess
import sys

STATIC_VAR = re.compile(r'^(const secp256k1_\w+ (?:\* const )?secp256k1_\w+ = )')
INCLUDE = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')


IF = re.compile(r'^\s*#\s*if')
ENDIF = re.compile(r'^\s*#\s*endif')
DIRECTIVE = re.compile(r'^\s*#')


def has_guard(lines):
    for line in lines:
        if DIRECTIVE.match(line):
            return re.match(r'^\s*#\s*ifndef\s', line) is not None
    return False


def inline(path, stack, depth, done):
    """The text of path with its includes expanded.

    A header is expanded once more for every #include of it, except when an
    earlier expansion sat outside every #if (depth 0, a file's own include
    guard not counted): that copy was compiled, so its guard turns any later
    one into nothing and the text is left out. A header first met inside an
    #if may have been skipped there, so it is expanded again where it is
    met next.
    """
    real = os.path.realpath(path)
    if real in stack:
        raise SystemExit("include cycle at " + path)
    with open(path, encoding="utf-8") as f:
        lines = f.readlines()
    local = -1 if has_guard(lines) else 0
    out = []
    base = os.path.dirname(path)
    for line in lines:
        m = INCLUDE.match(line)
        if m:
            target = os.path.normpath(os.path.join(base, m.group(1)))
            if not os.path.exists(target):
                raise SystemExit("missing include %s from %s" % (m.group(1), path))
            treal = os.path.realpath(target)
            if treal in done:
                out.append("/* %s: already included */\n" % m.group(1))
                continue
            here = depth + max(local, 0)
            if here == 0:
                done.add(treal)
            out.append("/* ---- begin %s ---- */\n" % m.group(1))
            out.extend(inline(target, stack + [real], here, done))
            out.append("/* ---- end %s ---- */\n" % m.group(1))
            continue
        if IF.match(line):
            local += 1
        elif ENDIF.match(line):
            local -= 1
        out.append(line)
    if out and not out[-1].endswith("\n"):
        out[-1] += "\n"
    return out


def commit(repo):
    return subprocess.check_output(["git", "-C", repo, "rev-parse", "HEAD"], text=True).strip()


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    secp, donna = sys.argv[1], sys.argv[2]
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(here, "..", "..", "vm", "ByteCodeTranslator", "src",
                            "cn1_crypto_kernels_amalgamation.h")
    parts = []
    parts.append("/*\n * GENERATED by scripts/crypto-kernels/amalgamate.py -- do not edit.\n"
                 " *\n * libsecp256k1 %s (MIT, see its COPYING below)\n"
                 " * ed25519-donna %s (public domain)\n */\n" % (commit(secp), commit(donna)))
    parts.append("#ifndef CN1_CRYPTO_KERNELS_AMALGAMATION_H\n#define CN1_CRYPTO_KERNELS_AMALGAMATION_H\n\n")
    with open(os.path.join(secp, "COPYING"), encoding="utf-8") as f:
        parts.append("/*\n * libsecp256k1 COPYING:\n *\n" + "".join(" * " + l for l in f) + " */\n\n")
    parts.append("#define ENABLE_MODULE_RECOVERY 1\n#define ENABLE_MODULE_EXTRAKEYS 1\n"
                 "#define ENABLE_MODULE_SCHNORRSIG 1\n"
                 "#define ECMULT_WINDOW_SIZE 15\n#define COMB_BLOCKS 43\n#define COMB_TEETH 6\n"
                 "#define SECP256K1_API static\n\n")
    done = set()
    secp_start = len(parts)
    for name in ("src/secp256k1.c", "src/precomputed_ecmult.c", "src/precomputed_ecmult_gen.c"):
        parts.append("/* ======== libsecp256k1 %s ======== */\n" % name)
        parts.extend(inline(os.path.join(secp, name), [], 0, done))
    # The public API was made static above, so that a second libsecp256k1 in the same application
    # (a library bundling its own) cannot collide with this one; its variables are defined
    # without SECP256K1_API, so they are made static here to match their declarations.
    secp_end = len(parts)
    for i in range(secp_start, secp_end):
        parts[i] = STATIC_VAR.sub(r"static \1", parts[i])
    parts.append("\n#undef ALIGN\n")
    parts.append("\n#define ED25519_CUSTOMHASH 1\n#define ED25519_CUSTOMRANDOM 1\n"
                 "#define ED25519_SUFFIX _cn1\n\n")
    parts.append("/* ======== ed25519-donna ed25519.c ======== */\n")
    parts.extend(inline(os.path.join(donna, "ed25519.c"), [], 0, set()))
    parts.append("\n#endif /* CN1_CRYPTO_KERNELS_AMALGAMATION_H */\n")
    text = "".join(parts)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (out_path, len(text)))


if __name__ == "__main__":
    main()

package com.codenameone.examples.brickyard.domain;

import com.codename1.annotations.Column;
import com.codename1.annotations.Entity;
import com.codename1.annotations.Id;

/// A store receipt that was accepted, keyed by store and transaction so it is credited once.
@Entity
public class StorePurchase {
    @Id(autoIncrement = false)
    @Column(nullable = false, type = "VARCHAR(400)")
    private String id = "";

    @Column(nullable = false, type = "VARCHAR(190)")
    private String username = "";

    @Column(nullable = false, type = "VARCHAR(64)")
    private String sku = "";

    @Column(nullable = false)
    private long bricks;

    @Column(nullable = false)
    private int refunded;

    @Column(nullable = false)
    private long createdAt;

    public StorePurchase() {
    }

    public String getId() {
        return id;
    }

    public void setId(String id) {
        this.id = id;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getSku() {
        return sku;
    }

    public void setSku(String sku) {
        this.sku = sku;
    }

    public long getBricks() {
        return bricks;
    }

    public void setBricks(long bricks) {
        this.bricks = bricks;
    }

    public int getRefunded() {
        return refunded;
    }

    public void setRefunded(int refunded) {
        this.refunded = refunded;
    }

    public long getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(long createdAt) {
        this.createdAt = createdAt;
    }
}

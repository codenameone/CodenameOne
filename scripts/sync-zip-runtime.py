#!/usr/bin/env python3
"""Generate the standalone ParparVM ZIP sources. Use --check to detect drift.

JZlib's canonical sources remain in core. Relocation keeps JavaAPI standalone
and avoids dependencies on mobile core or duplicate runtime class names.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ENGINE = ('Adler32 CRC32 Checksum Deflate Deflater GZIPException GZIPHeader '
          'InfBlocks InfCodes InfTree Inflate Inflater JZlib StaticTree Tree ZStream').split()


def generated():
    for name in ENGINE:
        source = ROOT / 'CodenameOne/src/com/codename1/io/gzip' / (name + '.java')
        text = source.read_text().replace('package com.codename1.io.gzip;',
                                         'package com.codename1.impl.zip;')
        text = text.replace('@com.codename1.impl.SharedWithBackend\n', '')
        yield ROOT / 'vm/JavaAPI/src/com/codename1/impl/zip' / source.name, text
    source = ROOT / 'CodenameOne/src/com/codename1/io/zip/ZipArchiveOutputStream.java'
    text = source.read_text().replace('package com.codename1.io.zip;', 'package java.util.zip;')
    text = text.replace('@com.codename1.impl.SharedWithBackend\n', '')
    text = text.replace('ZipArchiveOutputStream', 'ZipOutputStream')
    text = text.replace('Streaming ZIP writer with optional Unix permissions. Works on the JVM and\n/// ParparVM.',
                        'Streaming ZIP writer for ParparVM.')
    # The permission overload belongs to the portable CN1 helper only.
    start = text.index('    /// Writes an entry with Unix')
    end = text.index('    private void putEntry', start)
    text = text[:start] + text[end:]
    yield ROOT / 'vm/JavaAPI/src/java/util/zip/ZipOutputStream.java', text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, text in generated():
        text = '\n'.join(line.rstrip() for line in text.splitlines()) + '\n'
        notice_end = text.index('*/') + 2
        text = text[:notice_end] + '\n// Generated by scripts/sync-zip-runtime.py; edit the canonical core source.' + text[notice_end:]
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        raise SystemExit('Stale generated sources:\n' + '\n'.join(stale))


if __name__ == '__main__':
    main()

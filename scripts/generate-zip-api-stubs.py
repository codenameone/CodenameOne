#!/usr/bin/env python3
"""Generate mobile compile-time ZIP API stubs from compiled ParparVM classes.
Run after building vm/JavaAPI, with JAVA_HOME pointing at JDK 8.
These stubs describe the common API; actual ports supply the implementation.
"""
import argparse
import os
from pathlib import Path
import re
import subprocess
ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
java_home = Path(os.environ['JAVA_HOME'])
for source in sorted((ROOT / 'vm/JavaAPI/src/java/util/zip').glob('*.java')):
    compiled = ROOT / 'vm/JavaAPI/target/classes/java/util/zip' / (source.stem + '.class')
    api = subprocess.check_output([str(java_home / 'bin/javap'), '-protected', '-constants', str(compiled)], text=True)
    lines = ['// Generated by scripts/generate-zip-api-stubs.py. Compile-time API only.', 'package java.util.zip;', '']
    is_interface = False
    for line in api.splitlines():
        if line.startswith('Compiled from '):
            continue
        if line.startswith('public '):
            is_interface = ' interface ' in line
            line = line.replace('java.util.zip.' + source.stem, source.stem, 1)
        elif '(' in line:
            line = line.replace('java.util.zip.' + source.stem + '(', source.stem + '(')
            if not is_interface:
                body = 'throw new RuntimeException("Compile-time stub");'
                # The JDK filter base classes require an explicit constructor call.
                if re.match(r'\s+public '+source.stem+r'\(', line) and source.stem in ('DeflaterOutputStream','InflaterInputStream','CheckedInputStream','CheckedOutputStream'):
                    body = 'super(null); ' + body
                elif re.match(r'\s+public '+source.stem+r'\(', line) and source.stem in ('GZIPOutputStream','ZipOutputStream','GZIPInputStream','ZipInputStream'):
                    body = 'super(null); ' + body
                # javap omits parameter names.
                start, end = line.index('('), line.index(')')
                types = line[start+1:end].split(', ')
                params = ', '.join(t+' arg'+str(i) for i,t in enumerate(types) if t)
                line = line[:start+1] + params + line[end:]
                line = line.rstrip(';') + ' { ' + body + ' }'
            else:
                start, end = line.index('('), line.index(')')
                params = ', '.join(t+' arg'+str(i) for i,t in enumerate(line[start+1:end].split(', ')) if t)
                line = line[:start+1] + params + line[end:]
        lines.append(line)
    text = '\n'.join(lines) + '\n'
    target = ROOT / 'Ports/CLDC11/src/java/util/zip' / source.name
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('Stale ZIP API stub: '+str(target))
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text)

package com.codenameone.examples.bazaar.web.security;

/// The content security policy hashes of the inline elements of the public
/// templates, written by `fingerprint.py` from the template sources.
///
/// A public page is the same bytes for every visitor and is cached by shared
/// caches, so it cannot carry a per-request nonce. Its one inline stylesheet is
/// allowed by the hash of its text instead. The hash comes from the template
/// source, never from a rendered response: hashing what a response happens to
/// contain would bless an inline element an attacker managed to inject.
/// `InlineHashesTest` renders a page and checks every hash here against it.
public final class InlineHashes {
    private InlineHashes() {
    }

    // BEGIN GENERATED by fingerprint.py -- do not edit
    public static final String[] PUBLIC_STYLES = {
        "'sha256-gw7Z5nDQeWTWKDSC+SUAYYpNc/gwpyusd3QouXdsbwo='",
    };
    // END GENERATED
}

#!/usr/bin/env python3
"""Copies the web app's assets from web-src/ into src/main/resources/static/
under names that carry their content hash, and points the templates at them.

    python3 fingerprint.py

A name like app.1a2b3c4d.css never changes its bytes, so the server sends it
with a year of immutable caching (see web/security/ImmutableAssets.java). Edit
the file in web-src/, run this, rebuild. WebAssetsTest fails when a template
names a file that is missing or whose bytes no longer match its name.
"""
import hashlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "web-src")
STATIC = os.path.join(HERE, "src", "main", "resources", "static")
TEMPLATES = os.path.join(HERE, "src", "main", "resources", "templates")
# Source file -> published stem and extension.
ASSETS = [("app.css", "app", "css"), ("app.js", "app", "js"),
          ("htmx.js", "htmx", "js"), ("shop.css", "shop", "css"), ("shop.js", "shop", "js"),
          ("chat.css", "chat", "css"), ("chat.js", "chat", "js"), ("rtc.js", "rtc", "js"),
          # Wallets and pay-later forms, on the pages that take a payment.
          ("pay.js", "pay", "js"),
          # The vendored 3D model viewer (MODEL-VIEWER-NOTICE.txt), loaded only by
          # a product page with a model.
          ("model-viewer.js", "model-viewer", "js")]

# Java sources that name an asset (pages answered without a view). Found by file
# name, not by path: a project generated from this sample has its own package.
REFERENCES = ["NotFoundPage.java", "ErrorPages.java"]
JAVA = os.path.join(HERE, "src", "main", "java")


def find_java(name, parent=None):
    """The path of the source file called name (inside a directory called parent,
    when given) under src/main/java, or None."""
    for root, _dirs, names in os.walk(JAVA):
        if name in names and (parent is None or os.path.basename(root) == parent):
            return os.path.join(root, name)
    return None


def main():
    renames = {}
    for source, stem, ext in ASSETS:
        path = os.path.join(SRC, source)
        if not os.path.exists(path):
            continue
        data = open(path, "rb").read()
        digest = hashlib.sha256(data).hexdigest()[:8]
        name = "%s.%s.%s" % (stem, digest, ext)
        pattern = re.compile(r"^%s\.[0-9a-f]{8}\.%s$" % (re.escape(stem), ext))
        for old in os.listdir(STATIC):
            if pattern.match(old) and old != name:
                os.remove(os.path.join(STATIC, old))
        with open(os.path.join(STATIC, name), "wb") as out:
            out.write(data)
        renames[(stem, ext)] = name
    files = [os.path.join(TEMPLATES, t) for t in os.listdir(TEMPLATES)]
    files += [p for p in (find_java(n) for n in REFERENCES) if p]
    for path in files:
        if not os.path.exists(path):
            continue
        text = open(path, encoding="utf-8").read()
        new = text
        for (stem, ext), name in renames.items():
            new = re.sub(r"/static/%s\.[0-9a-f]{8}\.%s" % (re.escape(stem), ext),
                         "/static/" + name, new)
        if new != text:
            with open(path, "w", encoding="utf-8") as out:
                out.write(new)
    write_inline_hashes()
    for key, name in sorted(renames.items()):
        print(name)
    return 0


# Templates whose pages are public (one copy for every visitor, cached by shared
# caches): their inline <style> elements are allowed by hash instead of nonce.
PUBLIC_TEMPLATES = ["layout.html"]
HASHES_NAME = "InlineHashes.java"


def write_inline_hashes():
    """Writes the CSP hash of every inline <style> of the public templates into
    InlineHashes.java, so the policy of a public page needs no per-request
    nonce. InlineHashesTest renders a page and checks the hash against it."""
    import base64
    found = []
    for t in PUBLIC_TEMPLATES:
        text = open(os.path.join(TEMPLATES, t), encoding="utf-8").read()
        for body in re.findall(r"<style[^>]*>(.*?)</style>", text, re.S):
            digest = base64.b64encode(hashlib.sha256(body.encode("utf-8")).digest()).decode()
            found.append("'sha256-%s'" % digest)
    hashes = find_java(HASHES_NAME, "security")
    header = open(hashes, encoding="utf-8").read().split("// BEGIN GENERATED")[0]
    body = "// BEGIN GENERATED by fingerprint.py -- do not edit\n"
    body += "    public static final String[] PUBLIC_STYLES = {\n"
    for h in found:
        body += "        \"%s\",\n" % h
    body += "    };\n    // END GENERATED\n}\n"
    with open(hashes, "w", encoding="utf-8") as out:
        out.write(header + body)


if __name__ == "__main__":
    sys.exit(main())

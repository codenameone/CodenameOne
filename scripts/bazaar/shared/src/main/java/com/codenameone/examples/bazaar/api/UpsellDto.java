import com.codename1.annotations.Mapped;

/// The post-purchase offer. For the merchant only `productId` matters (empty
/// for none); for a shopper the rest describes the offer, and `orderNumber`
/// is the add-on order once taken (0 while it is still on offer).
@Mapped
public record UpsellDto(
        String productId,
        String title,
        long priceCents,
        int orderNumber) {
}

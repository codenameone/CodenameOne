// The Spring Boot half of the headless comparison: the same two routes on
// spring-boot-starter-web (Tomcat), as a Java team would write the service.
package bench;

import java.util.Map;

import org.springframework.boot.SpringApplication;
import org.springframework.boot.autoconfigure.SpringBootApplication;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RestController;

@SpringBootApplication
@RestController
public class Bench {
    @GetMapping(value = "/plaintext", produces = "text/plain")
    public String plaintext() {
        return "Hello, World!";
    }

    @GetMapping("/json")
    public Map<String, String> json() {
        return Map.of("message", "Hello, World!");
    }

    public static void main(String[] args) {
        SpringApplication.run(Bench.class, args);
    }
}

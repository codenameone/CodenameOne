"""Regenerate the data section of the runtime's unicodedata module.

The source of truth is the host CPython's own unicodedata module (which is
built from the Unicode Character Database), so run this with the CPython
whose Unicode version the runtime should report:

    python3 scripts/python/gen-unicodedata.py

It rewrites everything between the BEGIN/END GENERATED DATA markers of
maven/python-transpiler/src/main/resources/com/codename1/python/stdlib/unicodedata.py.
"""

import base64
import os
import re
import unicodedata as u
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TARGET = os.path.join(ROOT, "maven", "python-transpiler", "src", "main", "resources",
                      "com", "codename1", "python", "stdlib", "unicodedata.py")
CHUNK = 30000
MAX = 0x110000
SBASE, SCOUNT = 0xAC00, 11172


def varint(out, v):
    while v >= 128:
        out.append((v & 127) | 128)
        v >>= 7
    out.append(v)


def emit(lines, name, data):
    text = base64.b64encode(zlib.compress(bytes(data), 9)).decode("ascii")
    lines.append(name + " = (")
    for i in range(0, len(text), CHUNK):
        lines.append('    "' + text[i:i + CHUNK] + '",')
    lines.append(")")


def main():
    lines = ["# Data derived from the Unicode Character Database, Unicode " + u.unidata_version + ",",
             "# copyright Unicode, Inc., Unicode License v3. Generated by",
             "# scripts/python/gen-unicodedata.py from CPython's unicodedata.",
             "unidata_version = " + repr(u.unidata_version)]

    # properties as runs of records
    recs, rec_ids, runs = [], {}, bytearray()
    prev, length = None, 0
    for cp in range(MAX):
        c = chr(cp)
        r = (u.category(c), u.bidirectional(c), u.combining(c), u.mirrored(c), u.east_asian_width(c))
        if r != prev:
            if prev is not None:
                varint(runs, length)
                varint(runs, rec_ids[prev])
            if r not in rec_ids:
                rec_ids[r] = len(recs)
                recs.append(r)
            prev, length = r, 0
        length += 1
    varint(runs, length)
    varint(runs, rec_ids[prev])
    emit(lines, "_D_RECORDS", "\n".join("%s,%s,%d,%d,%s" % r for r in recs).encode("ascii"))
    emit(lines, "_D_RUNS", runs)

    # names: algorithmic ranges, then tokenized explicit names
    ranges, named = [], []
    for cp in range(MAX):
        n = u.name(chr(cp), None)
        if n is None or SBASE <= cp < SBASE + SCOUNT:
            continue
        h = "%04X" % cp
        if n.endswith("-" + h):
            prefix = n[:-len(h)]
            if ranges and ranges[-1][0] == prefix and ranges[-1][2] == cp - 1:
                ranges[-1][2] = cp
            else:
                ranges.append([prefix, cp, cp])
        else:
            named.append((cp, n))
    # front coding: one character (chr(48 + k)) for the k leading characters
    # shared with the previous name, then the rest of the name
    cps, text, last, prev = bytearray(), [], -1, ""
    for cp, n in named:
        varint(cps, cp - last)
        last = cp
        k = 0
        while k < len(n) and k < len(prev) and k < 60 and n[k] == prev[k]:
            k += 1
        text.append(chr(48 + k) + n[k:])
        prev = n
    emit(lines, "_D_NAMES", "\n".join(text).encode("ascii"))
    emit(lines, "_D_NAME_CPS", cps)
    lines.append("_NAME_RANGES = [")
    for p, a, b in ranges:
        lines.append("    (%r, 0x%X, 0x%X)," % (p, a, b))
    lines.append("]")

    # decompositions, numerics, composition exclusions
    dec, num, excl, last, nlast = [], [], [], 0, 0
    for cp in range(MAX):
        c = chr(cp)
        d = "" if SBASE <= cp < SBASE + SCOUNT else u.decomposition(c)
        if d:
            dec.append("%X %s" % (cp - last, d))
            last = cp
            parts = d.split(" ")
            if not parts[0].startswith("<") and len(parts) == 2 and u.normalize("NFC", c) != c:
                excl.append(cp)
        nv = u.numeric(c, None)
        if nv is not None:
            de, di = u.decimal(c, None), u.digit(c, None)
            num.append("%X:%s:%s:%r" % (cp - nlast, "" if de is None else de, "" if di is None else di, nv))
            nlast = cp
    emit(lines, "_D_DECOMP", "\n".join(dec).encode("ascii"))
    emit(lines, "_D_NUMERIC", "\n".join(num).encode("ascii"))
    lines.append("_COMPOSITION_EXCLUSIONS = [")
    for i in range(0, len(excl), 8):
        lines.append("    " + ", ".join("0x%X" % x for x in excl[i:i + 8]) + ",")
    lines.append("]")

    with open(TARGET, encoding="ascii") as f:
        src = f.read()
    begin, end = "# --- BEGIN GENERATED DATA ---\n", "# --- END GENERATED DATA ---\n"
    a, b = src.index(begin) + len(begin), src.index(end)
    src = src[:a] + "\n".join(lines) + "\n" + src[b:]
    with open(TARGET, "w", encoding="ascii", newline="\n") as f:
        f.write(src)
    print("records=%d runs=%d names=%d ranges=%d decomp=%d numeric=%d excl=%d size=%d"
          % (len(recs), len(runs), len(named), len(ranges), len(dec), len(num), len(excl), len(src)))


if __name__ == "__main__":
    main()

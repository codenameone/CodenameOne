using UnityEngine;

// Turns its object at a steady rate. In a screenshot it is what shows that
// the frames were stepped: after a known number of them of a known length
// the angle is one number, and at any other count it is another.
public class Spin : MonoBehaviour
{
    public float degreesPerSecond = 40f;

    private void Update()
    {
        transform.Rotate(0f, 0f, degreesPerSecond * Time.deltaTime);
    }
}

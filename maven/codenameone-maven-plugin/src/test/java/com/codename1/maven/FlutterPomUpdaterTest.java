package com.codename1.maven;

import org.junit.jupiter.api.Test;

import java.io.File;
import java.nio.file.Files;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/// cn1:import-flutter-project in a project generated by the current
/// archetype, which already carries the `transcode-flutter` execution active
/// but the runtime dependency commented out, and in one that predates the
/// feature entirely.
public class FlutterPomUpdaterTest {

    private static String read(String path) throws Exception {
        return new String(Files.readAllBytes(new File(path).toPath()), "UTF-8");
    }

    @Test
    public void uncommentsTheCurrentArchetypesDependency() throws Exception {
        String current = read("../cn1app-archetype/src/main/resources/archetype-resources/common/pom.xml");
        assertTrue(current.contains("<artifactId>codenameone-flutter-runtime</artifactId>"),
                "the archetype must still ship the commented-out dependency this test targets");
        FlutterPomUpdater u = new FlutterPomUpdater(current);
        assertTrue(u.manual.isEmpty(), u.manual.toString());
        assertTrue(u.changed);
        assertFalse(u.pom.replaceAll("(?s)<!--.*?-->", "").indexOf("codenameone-flutter-runtime") < 0,
                "the dependency must be active, not still commented out");
        assertTrue(u.pom.contains("<goal>transcode-flutter</goal>"));

        // Wired once: a second import changes nothing further.
        FlutterPomUpdater again = new FlutterPomUpdater(u.pom);
        assertFalse(again.changed);
        assertTrue(again.manual.isEmpty());
        assertEquals(u.pom, again.pom);
    }

    @Test
    public void wiresALegacyPomWithNeitherAnchorPresent() {
        String legacy = "<project><build><plugins>\n"
                + "    <plugin>\n"
                + "        <groupId>com.codenameone</groupId>\n"
                + "        <artifactId>codenameone-maven-plugin</artifactId>\n"
                + "        <executions>\n"
                + "        </executions>\n"
                + "    </plugin>\n"
                + "</plugins></build>\n"
                + "<dependencies>\n"
                + "</dependencies>\n"
                + "</project>\n";
        FlutterPomUpdater u = new FlutterPomUpdater(legacy);
        assertTrue(u.manual.isEmpty(), u.manual.toString());
        assertTrue(u.changed);
        assertTrue(u.pom.contains("<artifactId>codenameone-flutter-runtime</artifactId>"));
        assertTrue(u.pom.contains("<goal>transcode-flutter</goal>"));

        FlutterPomUpdater again = new FlutterPomUpdater(u.pom);
        assertFalse(again.changed);
        assertTrue(again.manual.isEmpty());
    }

    @Test
    public void neverWiresTheGoalIntoALaterPlugin() {
        String pom = "<project><dependencies></dependencies><build><plugins>\n"
                + "    <plugin>\n"
                + "        <groupId>com.codenameone</groupId>\n"
                + "        <artifactId>codenameone-maven-plugin</artifactId>\n"
                + "    </plugin>\n"
                + "    <plugin>\n"
                + "        <artifactId>maven-antrun-plugin</artifactId>\n"
                + "        <executions>\n"
                + "        </executions>\n"
                + "    </plugin>\n"
                + "</plugins></build></project>\n";
        FlutterPomUpdater u = new FlutterPomUpdater(pom);
        assertFalse(u.pom.contains("<goal>transcode-flutter</goal>"), u.pom);
        boolean named = false;
        for (String m : u.manual) {
            named |= m.contains("transcode-flutter");
        }
        assertTrue(named, u.manual.toString());
    }

    @Test
    public void namesWhatAPomWithoutTheAnchorsNeeds() {
        FlutterPomUpdater u = new FlutterPomUpdater("<project><build/></project>");
        assertFalse(u.changed);
        assertEquals(2, u.manual.size(), u.manual.toString());
    }
}

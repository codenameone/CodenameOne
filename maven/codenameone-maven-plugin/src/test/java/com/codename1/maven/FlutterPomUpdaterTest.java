package com.codename1.maven;

import org.junit.jupiter.api.Test;

import java.io.File;
import java.nio.file.Files;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/// cn1:import-flutter-project in a project generated by the current
/// archetype, which already carries the `transcode-flutter` execution active
/// but the runtime dependency commented out, and in one that predates the
/// feature entirely.
public class FlutterPomUpdaterTest {

    private static String read(String path) throws Exception {
        return new String(Files.readAllBytes(new File(path).toPath()), "UTF-8");
    }

    @Test
    public void uncommentsTheCurrentArchetypesDependency() throws Exception {
        String current = read("../cn1app-archetype/src/main/resources/archetype-resources/common/pom.xml");
        assertTrue(current.contains("<artifactId>codenameone-flutter-runtime</artifactId>"),
                "the archetype must still ship the commented-out dependency this test targets");
        FlutterPomUpdater u = new FlutterPomUpdater(current);
        assertTrue(u.manual.isEmpty(), u.manual.toString());
        assertTrue(u.changed);
        assertFalse(u.pom.replaceAll("(?s)<!--.*?-->", "").indexOf("codenameone-flutter-runtime") < 0,
                "the dependency must be active, not still commented out");
        assertTrue(u.pom.contains("<goal>transcode-flutter</goal>"));

        // Wired once: a second import changes nothing further.
        FlutterPomUpdater again = new FlutterPomUpdater(u.pom);
        assertFalse(again.changed);
        assertTrue(again.manual.isEmpty());
        assertEquals(u.pom, again.pom);
    }

    /// A project generated for Java 8 compiles at -source 8, and the transpiled
    /// Flutter sources are Java 17 (records): the import raises the level.
    @Test
    public void raisesAJava8CompilerLevelTo17() {
        String pom = "<project><build><plugins>\n"
                + "    <plugin>\n"
                + "        <artifactId>maven-compiler-plugin</artifactId>\n"
                + "        <configuration>\n"
                + "            <source>1.8</source>\n"
                + "            <target>8</target>\n"
                + "        </configuration>\n"
                + "    </plugin>\n"
                + "    <plugin><artifactId>other</artifactId><configuration><source>5</source></configuration></plugin>\n"
                + "</plugins></build></project>\n";
        String raised = FlutterPomUpdater.raiseCompilerLevel(pom);
        assertTrue(raised.contains("<source>17</source>"), raised);
        assertTrue(raised.contains("<target>17</target>"), raised);
        assertTrue(raised.contains("<source>5</source>"), "another plugin's configuration is not touched");
        assertEquals(raised, FlutterPomUpdater.raiseCompilerLevel(raised), "17 stays 17");
        String prop = pom.replace("<source>1.8</source>", "<source>${javaVersion}</source>");
        assertTrue(FlutterPomUpdater.raiseCompilerLevel(prop).contains("<source>${javaVersion}</source>"));

        assertEquals("a=1\ncodename1.arg.java.version=17\n",
                FlutterPomUpdater.raiseSettingsJavaLevel("a=1\ncodename1.arg.java.version=8\n"));
        assertEquals("codename1.arg.java.version=21\n",
                FlutterPomUpdater.raiseSettingsJavaLevel("codename1.arg.java.version=21\n"));
    }

    /// A runtime named only in dependencyManagement is not on the classpath: the
    /// import must still add the real dependency.
    @Test
    public void aManagedOnlyRuntimeStillGetsTheRealDependency() {
        String pom = "<project>\n"
                + "<dependencyManagement><dependencies>\n"
                + "    <dependency><groupId>com.codenameone</groupId>"
                + "<artifactId>codenameone-flutter-runtime</artifactId><version>1</version></dependency>\n"
                + "</dependencies></dependencyManagement>\n"
                + "<build><plugins><plugin><groupId>com.codenameone</groupId>"
                + "<artifactId>codenameone-maven-plugin</artifactId><executions>"
                + "<execution><goals><goal>transcode-flutter</goal></goals></execution>"
                + "</executions></plugin></plugins></build>\n"
                + "<dependencies>\n"
                + "</dependencies>\n"
                + "</project>\n";
        assertFalse(FlutterPomUpdater.declaresTopLevelRuntime(pom));
        FlutterPomUpdater u = new FlutterPomUpdater(pom);
        assertTrue(u.manual.isEmpty(), u.manual.toString());
        assertTrue(u.changed);
        assertTrue(FlutterPomUpdater.declaresTopLevelRuntime(u.pom), u.pom);
    }

    @Test
    public void wiresALegacyPomWithNeitherAnchorPresent() {
        String legacy = "<project><build><plugins>\n"
                + "    <plugin>\n"
                + "        <groupId>com.codenameone</groupId>\n"
                + "        <artifactId>codenameone-maven-plugin</artifactId>\n"
                + "        <executions>\n"
                + "        </executions>\n"
                + "    </plugin>\n"
                + "</plugins></build>\n"
                + "<dependencies>\n"
                + "</dependencies>\n"
                + "</project>\n";
        FlutterPomUpdater u = new FlutterPomUpdater(legacy);
        assertTrue(u.manual.isEmpty(), u.manual.toString());
        assertTrue(u.changed);
        assertTrue(u.pom.contains("<artifactId>codenameone-flutter-runtime</artifactId>"));
        assertTrue(u.pom.contains("<goal>transcode-flutter</goal>"));

        FlutterPomUpdater again = new FlutterPomUpdater(u.pom);
        assertFalse(again.changed);
        assertTrue(again.manual.isEmpty());
    }

    @Test
    public void neverWiresTheGoalIntoALaterPlugin() {
        String pom = "<project><dependencies></dependencies><build><plugins>\n"
                + "    <plugin>\n"
                + "        <groupId>com.codenameone</groupId>\n"
                + "        <artifactId>codenameone-maven-plugin</artifactId>\n"
                + "    </plugin>\n"
                + "    <plugin>\n"
                + "        <artifactId>maven-antrun-plugin</artifactId>\n"
                + "        <executions>\n"
                + "        </executions>\n"
                + "    </plugin>\n"
                + "</plugins></build></project>\n";
        FlutterPomUpdater u = new FlutterPomUpdater(pom);
        assertFalse(u.pom.contains("<goal>transcode-flutter</goal>"), u.pom);
        boolean named = false;
        for (String m : u.manual) {
            named |= m.contains("transcode-flutter");
        }
        assertTrue(named, u.manual.toString());
    }

    @Test
    public void namesWhatAPomWithoutTheAnchorsNeeds() {
        FlutterPomUpdater u = new FlutterPomUpdater("<project><build/></project>");
        assertFalse(u.changed);
        assertEquals(2, u.manual.size(), u.manual.toString());
    }

    /// A pom that pins transitive versions declares <dependencyManagement>
    /// (with its own nested <dependencies>) before its real, top-level
    /// <dependencies> -- legal, and common. The runtime dependency must land
    /// in the top-level one: a plain indexOf("<dependencies>") matches
    /// whichever comes first in the file, which spliced it into
    /// dependencyManagement, where Maven never adds it to the classpath.
    @Test
    public void insertsIntoTopLevelDependenciesNotDependencyManagement() {
        String pom = "<project>\n"
                + "    <dependencyManagement>\n"
                + "        <dependencies>\n"
                + "            <dependency>\n"
                + "                <groupId>other</groupId>\n"
                + "                <artifactId>other-artifact</artifactId>\n"
                + "                <version>1.0</version>\n"
                + "            </dependency>\n"
                + "        </dependencies>\n"
                + "    </dependencyManagement>\n"
                + "    <dependencies>\n"
                + "    </dependencies>\n"
                + "    <build>\n"
                + "        <plugins>\n"
                + "            <plugin>\n"
                + "                <groupId>com.codenameone</groupId>\n"
                + "                <artifactId>codenameone-maven-plugin</artifactId>\n"
                + "                <executions>\n"
                + "                </executions>\n"
                + "            </plugin>\n"
                + "        </plugins>\n"
                + "    </build>\n"
                + "</project>\n";
        FlutterPomUpdater u = new FlutterPomUpdater(pom);
        assertTrue(u.manual.isEmpty(), u.manual.toString());
        assertTrue(u.changed);

        int dependencyManagementEnd = u.pom.indexOf("</dependencyManagement>");
        int runtimeDependency = u.pom.indexOf("codenameone-flutter-runtime");
        assertTrue(dependencyManagementEnd > 0 && runtimeDependency > 0, u.pom);
        assertTrue(runtimeDependency > dependencyManagementEnd,
                "the runtime dependency must land in the top-level <dependencies>, "
                        + "after </dependencyManagement> closes, not inside it:\n" + u.pom);

        String managementBlock = u.pom.substring(u.pom.indexOf("<dependencyManagement>"), dependencyManagementEnd);
        assertFalse(managementBlock.contains("codenameone-flutter-runtime"),
                "dependencyManagement must be left untouched:\n" + managementBlock);
        assertTrue(managementBlock.contains("other-artifact"));
    }
}

package com.codename1.maven;

import org.apache.maven.plugins.annotations.Execute;
import org.apache.maven.plugins.annotations.LifecyclePhase;
import org.apache.maven.plugins.annotations.Mojo;
import org.apache.maven.plugins.annotations.ResolutionScope;

/**
 * Fails unless the configured database is exactly at this build's migrations: nothing
 * pending, nothing edited, nothing missing. A check to run before a deployment.
 *
 * Forks the lifecycle up to process-classes first, as cn1:backend does: that is where the
 * scripts are compiled into the module.
 */
@Execute(phase = LifecyclePhase.PROCESS_CLASSES)
@Mojo(name = "migrate-validate", requiresDependencyResolution = ResolutionScope.RUNTIME)
public class MigrateValidateMojo extends AbstractMigrateMojo {
    @Override
    String command() {
        return "validate";
    }
}

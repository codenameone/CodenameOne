#!/usr/bin/env python3
# Generates UnicodeTables.java: the character properties and case mappings
# Python's str methods answer from, for the Basic Multilingual Plane, taken
# from the CPython that the conformance suite records against.
#
#   python3.13 maven/python-runtime/tools/gen_unicode_tables.py
#
# The runtime cannot ask java.lang.Character: on a device that class is the
# CLDC one, which knows ASCII and at most Latin-1, so "Ü".lower() and
# "Α".isupper() answered wrongly there while the JVM run passed.
import os
import sys
import unicodedata

if sys.version_info[:2] != (3, 13):
    sys.exit("run with Python 3.13 (the version the conformance .out files record)")

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "main", "java", "com", "codename1", "python",
                   "runtime", "UnicodeTables.java")

UPPER, LOWER, ALPHA, DECIMAL, DIGIT, NUMERIC, SPACE, CASED = (1 << i for i in range(8))


def flags(c):
    f = 0
    if c.isupper():
        f |= UPPER
    if c.islower():
        f |= LOWER
    if c.isalpha():
        f |= ALPHA
    if c.isdecimal():
        f |= DECIMAL
    if c.isdigit():
        f |= DIGIT
    if c.isnumeric():
        f |= NUMERIC
    if c.isspace():
        f |= SPACE
    if c.lower() != c or c.upper() != c or c.title() != c or c.isupper() or c.islower() \
            or unicodedata.category(c) == "Lt":
        f |= CASED
    return f


def lit(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == '\\':
            out.append('\\\\')
        elif 32 <= o < 127:
            out.append(ch)
        elif o == 10:
            out.append('\\n')
        elif o == 13:
            out.append('\\r')
        else:
            # Line breaks, the quote and the backslash are handled above: a
            # backslash-u escape of those is replaced before javac lexes the
            # literal. No octal, which PMD reads as suspicious before a digit.
            out.append('\\u%04x' % o)
    return '"' + ''.join(out) + '"'


def chunks(s, n=8000):
    return [s[i:i + n] for i in range(0, len(s), n)] or [""]


# Runs of equal flags: start, flags.
runs = []
prev = None
for cp in range(0x10000):
    f = 0 if 0xD800 <= cp <= 0xDFFF else flags(chr(cp))
    if f != prev:
        runs.append((cp, f))
        prev = f
flag_str = "".join(chr(s) + chr(f) for s, f in runs)


def mapping(fn):
    parts = []
    for cp in range(0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        m = fn(c)
        if m != c:
            parts.append(chr(cp) + chr(len(m)) + m)
    return "".join(parts)


tables = {
    "FLAGS": flag_str,
    "LOWER": mapping(str.lower),
    "UPPER": mapping(str.upper),
    "TITLE": mapping(str.title),
    "FOLD": mapping(str.casefold),
}

with open(os.path.join(HERE, "..", "src", "main", "java", "com", "codename1", "python",
                       "runtime", "PyStr.java"), encoding="ascii") as f:
    header = f.read().split("package ", 1)[0]

lines = [header.rstrip("\n"), "package com.codename1.python.runtime;", "",
         "/// Generated by `maven/python-runtime/tools/gen_unicode_tables.py` from",
         "/// the Unicode %s data of CPython %d.%d; do not edit by hand."
         % (unicodedata.unidata_version, sys.version_info[0], sys.version_info[1]),
         "///",
         "/// `FLAGS` is runs of (first char, property bits) over the Basic",
         "/// Multilingual Plane; each mapping table is entries of (char, length,",
         "/// mapped chars), in char order. [Unicode] decodes them.",
         "final class UnicodeTables {",
         "    private UnicodeTables() {",
         "    }", ""]
for name, data in tables.items():
    lines.append("    static final String[] %s = {" % name)
    for c in chunks(data):
        lines.append("        " + lit(c) + ",")
    lines.append("    };")
    lines.append("")
lines[-1] = "}"
with open(OUT, "w", encoding="ascii", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", OUT, {k: len(v) for k, v in tables.items()})

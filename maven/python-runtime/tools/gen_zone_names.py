#!/usr/bin/env python3
# Generates TimeZoneNames.java: the IANA zone keys zoneinfo accepts, taken
# from the CPython that the conformance suite records against.
#
#   python3.13 maven/python-runtime/tools/gen_zone_names.py
#
# The runtime cannot ask java.util.TimeZone whether a key exists: on a device
# the class is ParparVM's, whose getTimeZone answers a zone named after any
# ID it is given, so ZoneInfo("Not/AZone") was accepted there.
import os
import sys
import zoneinfo

if sys.version_info[:2] != (3, 13):
    sys.exit("run with Python 3.13 (the version the conformance .out files record)")

HERE = os.path.dirname(os.path.abspath(__file__))
RT = os.path.join(HERE, "..", "src", "main", "java", "com", "codename1", "python", "runtime")
names = sorted(zoneinfo.available_timezones())
with open(os.path.join(RT, "PyStr.java"), encoding="ascii") as f:
    header = f.read().split("package ", 1)[0]
lines = [header.rstrip("\n"), "package com.codename1.python.runtime;", "",
         "/// Generated by `maven/python-runtime/tools/gen_zone_names.py` from the",
         "/// zone keys CPython %d.%d's zoneinfo lists; do not edit by hand. Sorted, for"
         % sys.version_info[:2],
         "/// a binary search.",
         "final class TimeZoneNames {",
         "    private TimeZoneNames() {",
         "    }", "",
         "    static final String[] NAMES = {"]
lines += ['        "%s",' % n for n in names]
lines += ["    };", "}"]
with open(os.path.join(RT, "TimeZoneNames.java"), "w", encoding="ascii", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", len(names), "names")

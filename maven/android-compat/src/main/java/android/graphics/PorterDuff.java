package android.graphics;

/// Porter-Duff compositing modes.
public class PorterDuff {

    public enum Mode {
        CLEAR, SRC, DST, SRC_OVER, DST_OVER, SRC_IN, DST_IN, SRC_OUT, DST_OUT, SRC_ATOP, DST_ATOP, XOR,
        DARKEN, LIGHTEN, MULTIPLY, SCREEN, ADD, OVERLAY
    }

    /// The mode for the integer `tintMode` attribute value.
    public static Mode intToMode(int value) {
        switch (value) {
            case 3:
                return Mode.SRC_OVER;
            case 5:
                return Mode.SRC_IN;
            case 9:
                return Mode.SRC_ATOP;
            case 14:
                return Mode.MULTIPLY;
            case 15:
                return Mode.SCREEN;
            case 16:
                return Mode.ADD;
            default:
                return Mode.SRC_IN;
        }
    }
}

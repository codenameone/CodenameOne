package android.webkit;

import android.graphics.Bitmap;
import android.view.View;

/// Receives a web view's browser-chrome events: progress, the page title,
/// JavaScript dialogs and console messages.
///
/// The native view shows JavaScript dialogs itself, so `onJsAlert`,
/// `onJsConfirm` and `onJsPrompt` are not consulted; the page's console is
/// not forwarded either.
public class WebChromeClient {

    public interface CustomViewCallback {
        void onCustomViewHidden();
    }

    public WebChromeClient() {
    }

    public void onProgressChanged(WebView view, int newProgress) {
    }

    public void onReceivedTitle(WebView view, String title) {
    }

    public void onReceivedIcon(WebView view, Bitmap icon) {
    }

    public void onReceivedTouchIconUrl(WebView view, String url, boolean precomposed) {
    }

    public void onShowCustomView(View view, CustomViewCallback callback) {
    }

    public void onHideCustomView() {
    }

    public void onCloseWindow(WebView window) {
    }

    public boolean onJsAlert(WebView view, String url, String message, JsResult result) {
        return false;
    }

    public boolean onJsConfirm(WebView view, String url, String message, JsResult result) {
        return false;
    }

    public boolean onJsPrompt(WebView view, String url, String message, String defaultValue,
                              JsPromptResult result) {
        return false;
    }

    public boolean onJsBeforeUnload(WebView view, String url, String message, JsResult result) {
        return false;
    }

    public boolean onConsoleMessage(ConsoleMessage consoleMessage) {
        return false;
    }

    public Bitmap getDefaultVideoPoster() {
        return null;
    }

    public View getVideoLoadingProgressView() {
        return null;
    }
}

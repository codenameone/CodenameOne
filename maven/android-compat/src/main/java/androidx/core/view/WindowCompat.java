package androidx.core.view;

import android.view.View;
import android.view.Window;

/// Static helpers over `Window`.
public final class WindowCompat {

    public static final int FEATURE_ACTION_BAR = 8;
    public static final int FEATURE_ACTION_BAR_OVERLAY = 9;
    public static final int FEATURE_ACTION_MODE_OVERLAY = 10;

    private WindowCompat() {
    }

    /// Recorded on the window. Codename One always lays the content out
    /// inside the safe area, so drawing behind the system bars has no effect.
    public static void setDecorFitsSystemWindows(Window window, boolean decorFitsSystemWindows) {
        window.setDecorFitsSystemWindows(decorFitsSystemWindows);
    }

    public static WindowInsetsControllerCompat getInsetsController(Window window, View view) {
        return new WindowInsetsControllerCompat(window, view);
    }
}

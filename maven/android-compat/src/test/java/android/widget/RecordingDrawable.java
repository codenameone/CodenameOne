package android.widget;

import android.graphics.Canvas;
import android.graphics.ColorFilter;
import android.graphics.PixelFormat;
import android.graphics.Rect;
import android.graphics.drawable.Drawable;

import java.util.ArrayList;
import java.util.List;

/// A drawable of a fixed intrinsic size that records the bounds of every draw,
/// so a test can see where a view placed it without a real canvas.
final class RecordingDrawable extends Drawable {
    final List<Rect> drawn = new ArrayList<Rect>();
    private final int width;
    private final int height;

    RecordingDrawable(int width, int height) {
        this.width = width;
        this.height = height;
    }

    @Override
    public void draw(Canvas canvas) {
        drawn.add(new Rect(getBounds()));
    }

    @Override
    public int getIntrinsicWidth() {
        return width;
    }

    @Override
    public int getIntrinsicHeight() {
        return height;
    }

    @Override
    public void setAlpha(int alpha) {
    }

    @Override
    public void setColorFilter(ColorFilter colorFilter) {
    }

    @Override
    public int getOpacity() {
        return PixelFormat.TRANSLUCENT;
    }
}

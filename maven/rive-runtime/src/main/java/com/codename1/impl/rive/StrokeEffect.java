package com.codename1.impl.rive;

/// Port of `StrokeEffect`: a trim or dash that rewrites the path a paint
/// draws. Effects cache their output and recompute only when the source
/// path's version or their own properties change.
public interface StrokeEffect {
    /// The path to draw instead of `source`; `fill` when the owning paint
    /// is a fill.
    RivePath effectPath(RivePath source, boolean fill);

    /// Drops the cached output.
    void invalidateEffect();
}

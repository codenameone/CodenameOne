package com.codename1.compat.jdk;

/// A class that declares a `parallelStream()` of its own; see
/// [StreamSource], which is the same arrangement for `stream()`.
///
/// The two are separate because the JDK's are: a collection that overrides
/// `stream()` alone keeps the default `parallelStream()`, which does not go
/// through the override.
public interface ParallelStreamSource<T> {
    /// The stream the class itself answers.
    Stream<T> parallelStream();
}

"""PIL raster fonts. Only Pillow's built-in bitmap font is available.

`load_default()` returns that bitmap font: it is what Pillow returns when it
is built without FreeType. A Pillow with FreeType returns a scalable font
instead (Aileron), which this runtime does not have, so text drawn with
`load_default()` matches `ImageFont.load_default_imagefont()` in CPython.
`truetype()` raises, since no TrueType rasterizer is built in.
"""

import base64
import io
import struct

from PIL import Image


class ImageFont:
    """A PIL bitmap font: 256 glyphs cut from one mode "1" sheet."""

    def __init__(self):
        self.info = []
        self._glyphs = None
        self._sheet = None
        self._baseline = 0
        self._ysize = 0

    def _load_pilfont_data(self, file, image):
        if file.readline() != b"PILfont\n":
            raise SyntaxError("Not a PILfont file")
        file.readline()
        while True:
            s = file.readline()
            if not s or s == b"DATA\n":
                break
            self.info.append(s)
        data = file.read(256 * 20)
        if image.mode not in ("1", "L"):
            raise TypeError("invalid font image mode")
        glyphs = []
        y0 = y1 = 0
        for i in range(256):
            g = struct.unpack(">10h", data[i * 20:i * 20 + 20])
            glyphs.append(g)
            y0 = min(y0, g[3])
            y1 = max(y1, g[5])
        self._glyphs = glyphs
        self._sheet = image
        self._baseline = -y0
        self._ysize = y1 - y0

    def _width(self, text):
        return sum(self._glyphs[ord(c) & 255][0] for c in text)

    def getbbox(self, text, *args, **kwargs):
        return 0, 0, self._width(text), self._ysize

    def getlength(self, text, *args, **kwargs):
        return self._width(text)

    def getmask(self, text, mode="", *args, **kwargs):
        mask = Image.new(self._sheet.mode, (self._width(text), self._ysize), 0)
        x = 0
        b = self._baseline
        for c in text:
            dx, dy, x0, y0, x1, y1, sx0, sy0, sx1, sy1 = self._glyphs[ord(c) & 255]
            if sx1 > sx0 and sy1 > sy0:
                mask.paste(self._sheet.crop((sx0, sy0, sx1, sy1)), (x0 + x, y0 + b))
            x += dx
            b += dy
        return mask


def load_default_imagefont():
    f = ImageFont()
    f._load_pilfont_data(io.BytesIO(base64.b64decode(_COURB08_PIL)),
                         Image.open(io.BytesIO(base64.b64decode(_COURB08_PNG))))
    return f


def load_default(size=None):
    return load_default_imagefont()


def truetype(font=None, size=10, index=0, encoding="", layout_engine=None):
    raise OSError("cannot open resource: TrueType fonts are not supported")


def load(filename):
    raise OSError("cannot find font file: " + str(filename))



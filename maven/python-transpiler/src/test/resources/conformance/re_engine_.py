# The regex machine's corners: text outside the BMP, case-insensitive sets,
# ranges and back references, lazy and possessive repeats, look-behind,
# conditionals, empty-loop guards, and pos/endpos.
import re

def show(p, s, flags=0, how="search"):
    m = getattr(re.compile(p, flags), how)(s)
    print(p, repr(s), m and (m.group(0), m.groups(), m.span(), m.lastindex))

show(r"(\w+)\s(\w+)", "hello world")
show(r"x(.)y", "a\U0001F600x\U0001F601yz")
show(r"[\U0001F600-\U0001F64F]+", "ab\U0001F600\U0001F602c")
show(r"\U0001F600.", "\U0001F600\U0001F600!")
show(r"[a-z]+", "ABCdef", re.I)
show(r"[^A-Z]+", "ABCdef")
show(r"(ab)\1", "xxABab", re.I)
show(r"(?i)(straSSe)\1", "strasseSTRASSE")
show(r"a.*?b", "aXbYb")
show(r"a{2,3}?", "aaaa")
show(r"(?<=ab)c", "xabc")
show(r"(?<!ab)c", "abcxc")
show(r"(?=(\d+))\1x", "123x")
show(r"(?>a+)b", "aaab")
show(r"(?>a+)ab", "aaab")
show(r"a++b", "aaab")
show(r"(a)?(?(1)b|c)", "c")
show(r"(a*)*b", "aaab")
show(r"(a|)+b", "b")
show(r"^\w+$", "café", how="match")
show(r"^\w+$", "café", re.A, how="match")
show(r"\bfoo\b", "a foo.")
show(r"\Bo", "foo")
show(r"^b", "a\nb", re.M)
show(r"a$", "a\n")
show(r"\d+", "١٢x")
show(r"\d+", "١٢x", re.A)
show(r"abc", "xxabcabc", how="search")
print(re.compile(r"b+").search("abbbc", 2, 3).span())
print(re.compile(r"c").search("abc", 0, 2))
print(re.findall(r"\U0001F600|a", "a\U0001F600b\U0001F600"))
print(re.sub(r"(\w)(\w*)", lambda m: m.group(2) + m.group(1), "hello big world"))
print(re.split(r"\s*,\s*", "a , b,c ,d"))
print([m.span() for m in re.finditer(r"", "ab")])
print(re.fullmatch(r"[a-c]+", "abcab"), re.fullmatch(r"[a-c]+", "abcd"))

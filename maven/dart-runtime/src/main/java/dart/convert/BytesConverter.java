package dart.convert;

import dart.typed_data.Uint8List;

/**
 * The direction of a byte codec that produces bytes: {@code utf8.encoder} and
 * {@code base64.decoder}. {@code convert} is typed {@link Uint8List}.
 */
public final class BytesConverter extends ByteCodec {

    BytesConverter(int kind) {
        super(kind);
    }

    @Override
    public Uint8List convert(Object input) {
        return (Uint8List) super.convert(input);
    }
}

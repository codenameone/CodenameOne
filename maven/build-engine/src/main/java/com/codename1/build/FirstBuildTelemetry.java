package com.codename1.build;

import java.io.File;
import java.io.IOException;
import java.io.OutputStream;
import java.io.UnsupportedEncodingException;
import java.net.HttpURLConnection;
import java.net.URL;
import java.net.URLEncoder;
import java.nio.charset.Charset;
import java.nio.file.Files;
import java.util.LinkedHashMap;
import java.util.Locale;
import java.util.Map;

/// Build progress reporting for a project generated by the Codename One Initializr
/// or the Build Cloud starter, when it is built from an IDE or from the command
/// line rather than through its `build.sh` / `build.bat` launcher.
///
/// The launchers already report a build's start and how it ended, so a first build
/// that dies on the developer's machine is visible instead of silent. Most
/// developers never run them: they open the project in IntelliJ, Eclipse, NetBeans
/// or VS Code, whose run configurations call Maven or Gradle directly. This class
/// gives those builds the same two reports, from the Maven lifecycle participant and
/// the Gradle settings plugin.
///
/// Nothing is sent unless the project opts in: the generator writes two properties,
/// [#PROJECT_PROPERTY] (the same anonymous id the launchers send, never the package
/// name) and [#EVENTS_PROPERTY] (where to send it). A project anyone else creates has
/// neither and reports nothing. `CN1_TELEMETRY=0` turns it off, as it does for the
/// launchers, and a build the launcher started is left to the launcher
/// ([#LAUNCHER_ENV]) so it is not counted twice.
///
/// The fields are the launchers' own -- the id, the target, the OS family, the Java
/// major version, the exit code, one word for why the build stopped, its duration --
/// plus which tool ran the build. Never code, paths, user names or build output. Each
/// report is one request with a three second limit, and any failure is ignored: this
/// can never change a build's outcome.
public final class FirstBuildTelemetry {
    /// The anonymous project id to report, written by the project generator.
    public static final String PROJECT_PROPERTY = "cn1.telemetry.project";
    /// The endpoint the reports go to, written by the project generator.
    public static final String EVENTS_PROPERTY = "cn1.telemetry.events";
    /// Set to 0 to turn reporting off, the same switch the launchers read.
    public static final String OPT_OUT_ENV = "CN1_TELEMETRY";
    /// Exported by `build.sh` / `build.bat`, which report the build themselves.
    public static final String LAUNCHER_ENV = "CN1_LAUNCHER";

    private static final int TIMEOUT_MS = 3000;

    private final String endpoint;
    private final String project;
    private final String client;
    private final String target;
    private final long startedAt;

    private FirstBuildTelemetry(String endpoint, String project, String client, String target, long startedAt) {
        this.endpoint = endpoint;
        this.project = project;
        this.client = client;
        this.target = target;
        this.startedAt = startedAt;
    }

    /// The reporter for this build, or null when this build must not report: the
    /// project did not opt in, the developer opted out, or a launcher started it.
    ///
    /// @param endpoint the value of [#EVENTS_PROPERTY], or null
    /// @param project the value of [#PROJECT_PROPERTY], or null
    /// @param target what is being built, see [#target]
    /// @param env the process environment
    /// @param sysProps the build JVM's system properties
    public static FirstBuildTelemetry start(String endpoint, String project, String target,
            Map<String, String> env, Map<?, ?> sysProps) {
        if (isBlank(endpoint) || isBlank(project)) {
            return null;
        }
        if ("0".equals(trim(env.get(OPT_OUT_ENV))) || "false".equals(trim(asString(sysProps.get("cn1.telemetry"))))) {
            return null;
        }
        if (!isBlank(env.get(LAUNCHER_ENV))) {
            return null;
        }
        String url = endpoint.trim();
        if (!url.startsWith("https://") && !url.startsWith("http://")) {
            return null;
        }
        return new FirstBuildTelemetry(url, project.trim(), client(env, sysProps), token(target),
                System.currentTimeMillis());
    }

    /// A reporter rebuilt from the parts of one already [started](#start), for a build
    /// tool that reports the end of the build from a different object than the one
    /// that saw it begin (Gradle's flow actions are serialized with the build).
    public static FirstBuildTelemetry resume(String endpoint, String project, String target, String client,
            long startedAt) {
        return new FirstBuildTelemetry(endpoint, project, client, target, startedAt);
    }

    public String endpoint() {
        return endpoint;
    }

    public String project() {
        return project;
    }

    public String target() {
        return target;
    }

    public String client() {
        return client;
    }

    public long startedAt() {
        return startedAt;
    }

    /// Reports that the build started, without waiting for the request: a slow or
    /// unreachable server must not hold up the build that is just beginning.
    public void launched() {
        final Map<String, String> fields = common("launch");
        Thread t = new Thread(new Runnable() {
            @Override
            public void run() {
                post(fields);
            }
        }, "cn1-build-report");
        t.setDaemon(true);
        t.start();
    }

    /// Reports how the build ended. Waits for the request, at most three seconds,
    /// because the build is over and the JVM may exit as soon as this returns.
    ///
    /// @param failure the build's failure, or null for a successful build
    public void finished(Throwable failure) {
        finishedWith(failure == null ? null : reason(failure));
    }

    /// As [#finished(Throwable)], with the failure already reduced to its reason.
    ///
    /// @param failureReason the [reason](#reason) the build failed, or null when it succeeded
    public void finishedWith(String failureReason) {
        finishedWith(failureReason, true);
    }

    /// As [#finishedWith(String)], optionally without the duration -- for a build tool
    /// that cannot tell when this run of the build started (see FirstBuildTelemetryAction
    /// in the Gradle plugin).
    public void finishedWith(String failureReason, boolean withDuration) {
        Map<String, String> fields = common("exit");
        fields.put("exit", failureReason == null ? "0" : "1");
        fields.put("reason", failureReason == null ? "ok" : failureReason);
        if (withDuration) {
            fields.put("secs", Long.toString(Math.max(0, (System.currentTimeMillis() - startedAt) / 1000)));
        }
        post(fields);
    }

    private Map<String, String> common(String step) {
        Map<String, String> fields = new LinkedHashMap<String, String>();
        fields.put("pkg", project);
        fields.put("step", step);
        if (target != null) {
            fields.put("target", target);
        }
        fields.put("os", os());
        fields.put("java", javaMajor());
        fields.put("client", client);
        return fields;
    }

    /// The tool that ran the build. IntelliJ IDEA starts Maven with `idea.version`
    /// set and Gradle with `idea.active`; NetBeans passes `netbeans.execution`;
    /// Eclipse runs Maven inside its own OSGi runtime and Gradle through Buildship;
    /// VS Code marks its terminals. Anything else is the command line.
    public static String client(Map<String, String> env, Map<?, ?> sysProps) {
        if (sysProps.get("idea.version") != null || sysProps.get("idea.active") != null
                || env.containsKey("IDEA_INITIAL_DIRECTORY") || "JetBrains-JediTerm".equals(env.get("TERMINAL_EMULATOR"))) {
            return "intellij";
        }
        if (sysProps.get("netbeans.execution") != null || sysProps.get("netbeans.home") != null) {
            return "netbeans";
        }
        if (sysProps.get("osgi.framework") != null || sysProps.get("eclipse.home.location") != null
                || env.containsKey("ECLIPSE_HOME")) {
            return "eclipse";
        }
        if ("vscode".equals(env.get("TERM_PROGRAM")) || env.containsKey("VSCODE_PID")
                || env.containsKey("VSCODE_IPC_HOOK_CLI")) {
            return "vscode";
        }
        return "cli";
    }

    /// One word for why the build stopped, from the failure Maven or Gradle reports.
    /// The vocabulary is the launchers' (launcher-telemetry-sh.txt), matched against
    /// the exception chain rather than the console output. Order matters as it does
    /// there: TLS failures surface inside artifact transfer errors, and the build
    /// client's own refusals before the generic build failure.
    public static String reason(Throwable failure) {
        StringBuilder text = new StringBuilder();
        StringBuilder types = new StringBuilder();
        int depth = 0;
        for (Throwable t = failure; t != null && depth < 20; t = t.getCause(), depth++) {
            types.append(t.getClass().getName()).append('\n');
            if (t.getMessage() != null) {
                text.append(t.getMessage()).append('\n');
            }
            for (Throwable s : t.getSuppressed()) {
                types.append(s.getClass().getName()).append('\n');
                if (s.getMessage() != null) {
                    text.append(s.getMessage()).append('\n');
                }
            }
            if (t.getCause() == t) {
                break;
            }
        }
        String m = text.toString();
        String c = types.toString();
        if (has(m, "No compiler is provided in this environment",
                "JAVA_HOME environment variable is not defined correctly")) {
            return "no_jdk";
        }
        if (has(m, "invalid target release", "invalid source release", "Unsupported class file major version",
                "UnsupportedClassVersionError", "class file version",
                // maven-enforcer's requireJavaVersion, which the console starter uses
                "RequireJavaVersion")
                || m.matches("(?s).*release version \\d+ not supported.*")
                || has(c, "java.lang.UnsupportedClassVersionError")) {
            return "java_too_old";
        }
        if (has(m, "Browser login timed out")) {
            return "login_timeout";
        }
        if (has(m, "Cannot authenticate a non-interactive build", "Account login failed")) {
            return "login_failed";
        }
        if (has(m, "Compilation failure", "Compilation failed") || has(c, "CompilationFailureException")) {
            return "compile";
        }
        if (has(m, "PKIX path building failed", "unable to find valid certification path")
                || has(c, "javax.net.ssl.SSLHandshakeException", "javax.net.ssl.SSLException")) {
            return "tls";
        }
        if (has(m, "Could not transfer artifact", "Could not resolve", "Could not find artifact",
                "Non-resolvable parent POM", "Plugin not found", "Could not download", "Failed to fetch")
                || has(c, "java.net.UnknownHostException", "java.net.ConnectException",
                        "java.net.SocketTimeoutException")
                || has(c, "DependencyResolutionException", "ArtifactResolutionException",
                        "PluginResolutionException", "ModelResolutionException", "ResolveException")) {
            return "maven_download";
        }
        if (has(m, "Jar size limit reached", "Quota size limit reached", "exceeds 50MB", "exceeds 100MB")) {
            return "size_limit";
        }
        if (has(m, "certificate from Apple with the appropriate password is required",
                "App id for an iOS build MUST be defined", "Error reading the certificate file",
                "Error reading the provisioning profile")) {
            return "no_certificate";
        }
        if (has(m, "can't be empty", "The icon must be a 512x512", "Error reading the icon")) {
            return "project_config";
        }
        if (has(m, "Error connecting to s3", "Failed to upload to server", "General network error occured")) {
            return "upload_failed";
        }
        if (has(m, "Server Detailed Error Message", "Error! Server response code")) {
            return "server_refused";
        }
        return "build_failed";
    }

    static String os() {
        String name = System.getProperty("os.name", "").toLowerCase(Locale.ROOT);
        if (name.contains("mac")) {
            return "mac";
        }
        if (name.contains("win")) {
            return "windows";
        }
        if (name.contains("linux")) {
            try {
                File version = new File("/proc/version");
                if (version.isFile() && new String(Files.readAllBytes(version.toPath()), Charset.forName("UTF-8"))
                        .toLowerCase(Locale.ROOT).contains("microsoft")) {
                    return "wsl";
                }
            } catch (IOException | RuntimeException ignored) {
                // Not knowing about WSL leaves it reported as linux.
            }
            return "linux";
        }
        return "other";
    }

    static String javaMajor() {
        String v = System.getProperty("java.specification.version", "");
        if (v.startsWith("1.")) {
            v = v.substring(2);
        }
        return v.matches("\\d{1,3}") ? v : "unknown";
    }

    /// What is being built, as one short token: the build target when one was asked
    /// for (`android-device`, `javascript`, `local-javascript`, ...), otherwise the
    /// first goal or task the developer ran (`run`, `package`, ...).
    public static String target(String buildTarget, Iterable<String> goalsOrTasks) {
        if (!isBlank(buildTarget)) {
            return token(buildTarget);
        }
        if (goalsOrTasks != null) {
            for (String g : goalsOrTasks) {
                if (!isBlank(g)) {
                    String last = g.substring(g.lastIndexOf(':') + 1);
                    return token(last);
                }
            }
        }
        return null;
    }

    static String token(String v) {
        if (v == null) {
            return null;
        }
        String t = v.trim().toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9_.-]", "_");
        if (t.isEmpty()) {
            return null;
        }
        return t.length() > 32 ? t.substring(0, 32) : t;
    }

    private void post(Map<String, String> fields) {
        HttpURLConnection conn = null;
        try {
            byte[] body = form(fields).getBytes("UTF-8");
            conn = (HttpURLConnection) new URL(endpoint).openConnection();
            conn.setConnectTimeout(TIMEOUT_MS);
            conn.setReadTimeout(TIMEOUT_MS);
            conn.setRequestMethod("POST");
            conn.setDoOutput(true);
            conn.setRequestProperty("Content-Type", "application/x-www-form-urlencoded");
            OutputStream out = conn.getOutputStream();
            try {
                out.write(body);
            } finally {
                out.close();
            }
            conn.getResponseCode();
        } catch (Throwable ignored) {
            // Reporting is best effort and never touches the build.
        } finally {
            if (conn != null) {
                conn.disconnect();
            }
        }
    }

    static String form(Map<String, String> fields) throws UnsupportedEncodingException {
        StringBuilder sb = new StringBuilder();
        for (Map.Entry<String, String> e : fields.entrySet()) {
            if (e.getValue() == null) {
                continue;
            }
            if (sb.length() > 0) {
                sb.append('&');
            }
            sb.append(URLEncoder.encode(e.getKey(), "UTF-8")).append('=')
                    .append(URLEncoder.encode(e.getValue(), "UTF-8"));
        }
        return sb.toString();
    }

    private static boolean has(String haystack, String... needles) {
        for (String n : needles) {
            if (haystack.contains(n)) {
                return true;
            }
        }
        return false;
    }

    private static boolean isBlank(String s) {
        return s == null || s.trim().isEmpty();
    }

    private static String trim(String s) {
        return s == null ? null : s.trim();
    }

    private static String asString(Object o) {
        return o == null ? null : o.toString();
    }
}

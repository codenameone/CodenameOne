package com.codename1.flutter;

/**
 * The direction a scrollable's content grows in — Flutter's {@code AxisDirection}.
 *
 * <p>Named for where the content END lies, not where the finger moves: a vertical list
 * that scrolls downwards through its content is {@code down}.</p>
 */
public enum AxisDirection {
    up, right, down, left
}

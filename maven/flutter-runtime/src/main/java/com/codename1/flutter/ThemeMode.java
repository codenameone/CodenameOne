package com.codename1.flutter;

/**
 * Which of a {@link com.codename1.flutter.material.MaterialApp MaterialApp}'s
 * themes to use: {@code system} follows the platform dark-mode setting
 * (defaulting to light when the platform can't report it), {@code light} and
 * {@code dark} force one theme regardless of the platform.
 */
public enum ThemeMode {
    system, light, dark
}

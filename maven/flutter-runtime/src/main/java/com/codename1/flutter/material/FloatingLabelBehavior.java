package com.codename1.flutter.material;

/**
 * How a {@link TextField}'s floating label behaves — Flutter's
 * {@code FloatingLabelBehavior}. {@link #auto} floats the label on focus/input,
 * {@link #always} keeps it floated, {@link #never} keeps it inline as a hint.
 */
public enum FloatingLabelBehavior {
    never, auto, always
}

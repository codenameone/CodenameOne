package javafx.scene.layout;

/// How a background image fills the room its one copy leaves.
public enum BackgroundRepeat {
    /// Copies side by side from the position, cut off at the edges.
    REPEAT,
    /// As many whole copies as fit, spread out so the first and the last
    /// touch the edges.
    SPACE,
    /// Copies resized so that a whole number of them fits exactly.
    ROUND,
    /// One copy.
    NO_REPEAT
}

package javafx.scene.control;

/// Where the graphic of a labeled control sits relative to its text.
public enum ContentDisplay {
    /// Above the text.
    TOP,
    /// To the right of the text.
    RIGHT,
    /// Below the text.
    BOTTOM,
    /// To the left of the text.
    LEFT,
    /// Centred, over the text.
    CENTER,
    /// Only the graphic is shown.
    GRAPHIC_ONLY,
    /// Only the text is shown.
    TEXT_ONLY
}

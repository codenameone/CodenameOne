package javafx.stage;

/// How a stage blocks input to the other windows while it is showing.
public enum Modality {
    /// The stage blocks nothing.
    NONE,
    /// The stage blocks its owner and the owner's owners.
    WINDOW_MODAL,
    /// The stage blocks every other window of the application.
    APPLICATION_MODAL
}

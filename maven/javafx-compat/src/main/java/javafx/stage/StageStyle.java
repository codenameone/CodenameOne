package javafx.stage;

/// The decoration of a stage. It is honoured where the stage is a desktop
/// window; a stage shown as a form or a dialog has no decoration to
/// choose.
public enum StageStyle {
    /// The platform's title bar and border.
    DECORATED,
    /// No decoration.
    UNDECORATED,
    /// No decoration; shown as undecorated, without transparency.
    TRANSPARENT,
    /// The decoration of a utility window.
    UTILITY,
    /// A decoration with a uniform colour; shown as decorated.
    UNIFIED
}

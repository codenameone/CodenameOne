package javafx.event;

/// The ordered dispatchers an event travels through.
public interface EventDispatchChain {

    /// Adds a dispatcher after the others and returns the resulting chain.
    EventDispatchChain append(EventDispatcher eventDispatcher);

    /// Adds a dispatcher before the others and returns the resulting chain.
    EventDispatchChain prepend(EventDispatcher eventDispatcher);

    /// Sends an event through the chain, starting at its first dispatcher.
    /// Returns the resulting event, or `null` when it was consumed.
    Event dispatchEvent(Event event);
}

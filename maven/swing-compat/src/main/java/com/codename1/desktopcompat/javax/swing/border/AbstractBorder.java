package com.codename1.desktopcompat.javax.swing.border;

import com.codename1.desktopcompat.java.awt.Component;
import com.codename1.desktopcompat.java.awt.Graphics;
import com.codename1.desktopcompat.java.awt.Insets;
import com.codename1.desktopcompat.java.awt.Rectangle;

/// A border that takes no space and paints nothing, as the base the other
/// borders build on.
public abstract class AbstractBorder implements Border {

    @Override
    public void paintBorder(Component c, Graphics g, int x, int y, int width, int height) {
    }

    @Override
    public Insets getBorderInsets(Component c) {
        return getBorderInsets(c, new Insets(0, 0, 0, 0));
    }

    public Insets getBorderInsets(Component c, Insets insets) {
        insets.left = 0;
        insets.top = 0;
        insets.right = 0;
        insets.bottom = 0;
        return insets;
    }

    @Override
    public boolean isBorderOpaque() {
        return false;
    }

    public Rectangle getInteriorRectangle(Component c, int x, int y, int width, int height) {
        return getInteriorRectangle(c, this, x, y, width, height);
    }

    public static Rectangle getInteriorRectangle(Component c, Border b, int x, int y, int width, int height) {
        Insets in = b != null ? b.getBorderInsets(c) : new Insets(0, 0, 0, 0);
        return new Rectangle(x + in.left, y + in.top, width - in.right - in.left, height - in.top - in.bottom);
    }

    public int getBaseline(Component c, int width, int height) {
        if (width < 0 || height < 0) {
            throw new IllegalArgumentException("Width and height must be >= 0");
        }
        return -1;
    }
}

package com.codename1.desktopcompat.org.jdesktop.swingx.painter;

import com.codename1.desktopcompat.java.awt.Graphics2D;

/// Draws into a graphics on behalf of an object, usually a component.
///
/// The painter may change the state of `g` freely; a caller that needs it
/// afterwards hands over a copy. `object` may be `null`.
public interface Painter<T> {

    /// Paints into the rectangle `(0, 0, width, height)` of `g`.
    void paint(Graphics2D g, T object, int width, int height);
}

package com.codename1.desktopcompat.javax.swing;

import com.codename1.desktopcompat.javax.swing.event.ChangeEvent;
import com.codename1.desktopcompat.javax.swing.event.ChangeListener;
import com.codename1.desktopcompat.javax.swing.event.EventListenerList;
import java.util.EventListener;

/// The usual single selection model: an index, -1 for none, and a change
/// event each time it becomes a different one.
public class DefaultSingleSelectionModel implements SingleSelectionModel {

    protected ChangeEvent changeEvent;
    protected EventListenerList listenerList = new EventListenerList();

    private int index = -1;

    public DefaultSingleSelectionModel() {
    }

    @Override
    public int getSelectedIndex() {
        return index;
    }

    @Override
    public void setSelectedIndex(int index) {
        if (this.index != index) {
            this.index = index;
            fireStateChanged();
        }
    }

    @Override
    public void clearSelection() {
        setSelectedIndex(-1);
    }

    @Override
    public boolean isSelected() {
        return index != -1;
    }

    @Override
    public void addChangeListener(ChangeListener l) {
        listenerList.add(ChangeListener.class, l);
    }

    @Override
    public void removeChangeListener(ChangeListener l) {
        listenerList.remove(ChangeListener.class, l);
    }

    public ChangeListener[] getChangeListeners() {
        return listenerList.getListeners(ChangeListener.class);
    }

    protected void fireStateChanged() {
        ChangeListener[] ls = getChangeListeners();
        for (int i = ls.length - 1; i >= 0; i--) {
            if (changeEvent == null) {
                changeEvent = new ChangeEvent(this);
            }
            ls[i].stateChanged(changeEvent);
        }
    }

    public <T extends EventListener> T[] getListeners(Class<T> listenerType) {
        return listenerList.getListeners(listenerType);
    }
}

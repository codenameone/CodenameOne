    /// The code table of built-in encoding `slot`: 0 standard, 1 WinAnsi,
    /// 2 MacRoman, 3 Symbol, 4 ZapfDingbats. Kept behind a method so the
    /// long tables are not copied into every class that reads them.
    static String table(int slot) {
        return slot == 1 ? WIN_ANSI : slot == 2 ? MAC_ROMAN : slot == 3 ? SYMBOL : slot == 4 ? ZAPF_DINGBATS
                : STANDARD;
    }

    /// The glyph name to Unicode table.
    static String unicode() {
        return UNICODE;
    }

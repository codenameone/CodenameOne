    private static int[] categoryStarts;
    private static int[] categoryValues;
    private static int[] scriptStarts;
    private static int[] scriptValues;
    private static int[] alphabetic;
    private static int[] lowercase;
    private static int[] uppercase;
    private static int[] blockRanges;
    private static String[] scriptNames;
    private static String[] blockNames;

    private UnicodeTables() {
    }

    private static int[] decode(String s) {
        int[] out = new int[s.length()];
        int n = 0;
        int i = 0;
        while (i < s.length()) {
            int v = 0;
            int shift = 0;
            while (true) {
                int d = DIGITS.indexOf(s.charAt(i++));
                v |= (d & 31) << shift;
                shift += 5;
                if ((d & 32) == 0) {
                    break;
                }
            }
            out[n++] = v;
        }
        int[] exact = new int[n];
        System.arraycopy(out, 0, exact, 0, n);
        return exact;
    }

    /// Splits pairs of (delta, value) into starts and values.
    private static int[][] runs(String s) {
        int[] raw = decode(s);
        int[] starts = new int[raw.length / 2];
        int[] values = new int[raw.length / 2];
        int at = 0;
        for (int k = 0; k < starts.length; k++) {
            at += raw[2 * k];
            starts[k] = at;
            values[k] = raw[2 * k + 1];
        }
        return new int[][] {starts, values};
    }

    private static int[] toggles(String s) {
        int[] raw = decode(s);
        int at = 0;
        for (int k = 0; k < raw.length; k++) {
            at += raw[k];
            raw[k] = at;
        }
        return raw;
    }

    /// The index of the last entry of `starts` at or below `cp`.
    private static int floor(int[] starts, int cp) {
        int lo = 0;
        int hi = starts.length - 1;
        while (lo < hi) {
            int mid = (lo + hi + 1) >>> 1;
            if (starts[mid] <= cp) {
                lo = mid;
            } else {
                hi = mid - 1;
            }
        }
        return lo;
    }

    private static boolean in(int[] toggles, int cp) {
        if (cp < toggles[0]) {
            return false;
        }
        return (floor(toggles, cp) & 1) == 0;
    }

    /// The general category, as `Character.getType` numbers them.
    static synchronized int category(int cp) {
        if (categoryStarts == null) {
            int[][] r = runs(CATEGORIES);
            categoryStarts = r[0];
            categoryValues = r[1];
        }
        return categoryValues[floor(categoryStarts, cp)];
    }

    static synchronized boolean alphabetic(int cp) {
        if (alphabetic == null) {
            alphabetic = toggles(ALPHABETIC);
        }
        return in(alphabetic, cp);
    }

    static synchronized boolean lowercase(int cp) {
        if (lowercase == null) {
            lowercase = toggles(LOWERCASE);
        }
        return in(lowercase, cp);
    }

    static synchronized boolean uppercase(int cp) {
        if (uppercase == null) {
            uppercase = toggles(UPPERCASE);
        }
        return in(uppercase, cp);
    }

    /// The script of `cp`, as an index into the script names.
    static synchronized int scriptOf(int cp) {
        if (scriptStarts == null) {
            int[][] r = runs(SCRIPTS);
            scriptStarts = r[0];
            scriptValues = r[1];
        }
        return scriptValues[floor(scriptStarts, cp)];
    }

    /// The script `name` names, as `UnicodeScript.forName` reads it: its
    /// name or its ISO 15924 alias, in any case; -1 for none.
    static synchronized int script(String name) {
        if (scriptNames == null) {
            scriptNames = split(SCRIPT_NAMES, ' ');
        }
        String upper = asciiUpper(name);
        for (int k = 0; k < scriptNames.length; k++) {
            if (scriptNames[k].equals(upper)) {
                return k;
            }
        }
        String[] aliases = split(SCRIPT_ALIASES, ' ');
        for (int k = 0; k < aliases.length; k++) {
            int eq = aliases[k].indexOf('=');
            if (aliases[k].substring(0, eq).equals(upper)) {
                return Integer.parseInt(aliases[k].substring(eq + 1));
            }
        }
        return -1;
    }

    /// The first and last code point of the block `name` names, as
    /// `UnicodeBlock.forName` reads it; null for none.
    static synchronized int[] block(String name) {
        if (blockNames == null) {
            blockNames = split(BLOCK_NAMES, ';');
            blockRanges = decode(BLOCKS);
        }
        String upper = asciiUpper(name);
        int start = 0;
        for (int k = 0; k < blockNames.length; k++) {
            start += blockRanges[2 * k];
            String[] keys = split(blockNames[k], '|');
            for (int j = 0; j < keys.length; j++) {
                // Each name is also accepted with its spaces left out.
                if (keys[j].equals(upper) || withoutSpaces(keys[j]).equals(upper)) {
                    return new int[] {start, start + blockRanges[2 * k + 1]};
                }
            }
        }
        return null;
    }

    private static String withoutSpaces(String s) {
        if (s.indexOf(' ') < 0) {
            return s;
        }
        StringBuilder out = new StringBuilder(s.length());
        for (int k = 0; k < s.length(); k++) {
            if (s.charAt(k) != ' ') {
                out.append(s.charAt(k));
            }
        }
        return out.toString();
    }

    private static String asciiUpper(String s) {
        StringBuilder out = new StringBuilder(s.length());
        for (int k = 0; k < s.length(); k++) {
            char c = s.charAt(k);
            out.append(c >= 'a' && c <= 'z' ? (char) (c - 32) : c);
        }
        return out.toString();
    }

    private static String[] split(String s, char sep) {
        int n = 1;
        for (int k = 0; k < s.length(); k++) {
            if (s.charAt(k) == sep) {
                n++;
            }
        }
        String[] out = new String[n];
        int start = 0;
        int at = 0;
        for (int k = 0; k <= s.length(); k++) {
            if (k == s.length() || s.charAt(k) == sep) {
                out[at++] = s.substring(start, k);
                start = k + 1;
            }
        }
        return out;
    }

package com.codename1.ui.table;

/// Turns the values of a `GridColumn` into the text a cell shows, and the
/// text typed into an editor back into a value.
public interface GridFormatter {

    /// The text `value` is shown as; never null.
    String format(Object value);

    /// The value `text` stands for, given the value the cell held before.
    ///
    /// #### Returns
    ///
    /// the new value, or `previous` when the text cannot be read
    Object parse(String text, Object previous);
}

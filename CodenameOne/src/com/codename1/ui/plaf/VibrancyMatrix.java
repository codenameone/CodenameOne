    /// The vibrancy matrix for content tinted `rgb`, as 12 floats: three rows
    /// (red, green, blue) of `[r, g, b, offset]`, in 0..1 units, the layout
    /// Graphics.colorMatrixRegion takes.
    ///
    /// #### Parameters
    ///
    /// - `rgb`: the tint, 0xRRGGBB
    ///
    /// - `dark`: true for the dark appearance
    ///
    /// #### Returns
    ///
    /// a new 12-element matrix
    public static float[] forTint(int rgb, boolean dark) {
        double[] t = {((rgb >> 16) & 0xff) / 255.0, ((rgb >> 8) & 0xff) / 255.0, (rgb & 0xff) / 255.0};
        double mx = Math.max(t[0], Math.max(t[1], t[2]));
        double mn = Math.min(t[0], Math.min(t[1], t[2]));
        float[] m = new float[12];
        if (mx - mn < 1e-9) {
            double gi = mx * 15;
            int i = (int) Math.min(14, Math.floor(gi));
            double f = gi - i;
            double gain = GREY_GAIN[i] * (1 - f) + GREY_GAIN[i + 1] * f;
            double off = GREY_OFFSET[i] * (1 - f) + GREY_OFFSET[i + 1] * f;
            for (int r = 0; r < 3; r++) {
                m[r * 4 + r] = (float) gain;
                m[r * 4 + 3] = (float) off;
            }
            return m;
        }
        double e = 0.5 * mn / mx;
        if (dark) {
            double tt = t[0] * t[0] + t[1] * t[1] + t[2] * t[2];
            double a = 0.5 - e;
            for (int r = 0; r < 3; r++) {
                for (int c = 0; c < 3; c++) {
                    m[r * 4 + c] = (float) ((r == c ? e : 0) + a * t[c] / tt);
                }
                m[r * 4 + 3] = (float) t[r];
            }
            return m;
        }
        double alpha = lightAlpha(t, mx, mn);
        double s = (1 - t[0]) + (1 - t[1]) + (1 - t[2]);
        double c = (1 - alpha - e) / s;
        for (int r = 0; r < 3; r++) {
            for (int col = 0; col < 3; col++) {
                m[r * 4 + col] = (float) (c * (1 + t[r]) * (1 - t[col]) + (r == col ? e : 0));
            }
            m[r * 4 + 3] = (float) (alpha * (1 + t[r]) - 1 + e * t[r]);
        }
        return m;
    }

    /// Trilinear lookup of the light darkening alpha.
    static double lightAlpha(double[] t, double mx, double mn) {
        double md = t[0] + t[1] + t[2] - mx - mn;
        double chroma = mx - mn;
        double value = chroma < 1 ? mn / (1 - chroma) : 0;
        double hue = (md - mn) / chroma;
        double c255 = chroma * 255;
        int ci = CHROMA_NODES.length - 2;
        for (int i = 0; i < CHROMA_NODES.length - 1; i++) {
            if (c255 < CHROMA_NODES[i + 1]) {
                ci = i;
                break;
            }
        }
        double fc = (c255 - CHROMA_NODES[ci]) / (CHROMA_NODES[ci + 1] - CHROMA_NODES[ci]);
        int vi = VALUE_NODES.length - 2;
        for (int i = 0; i < VALUE_NODES.length - 1; i++) {
            if (value < VALUE_NODES[i + 1]) {
                vi = i;
                break;
            }
        }
        double fv = (value - VALUE_NODES[vi]) / (VALUE_NODES[vi + 1] - VALUE_NODES[vi]);
        double hx = hue * (HUE_NODES - 1);
        int wi = (int) Math.min(HUE_NODES - 2, Math.floor(hx));
        double fw = hx - wi;
        fc = clamp01(fc);
        fv = clamp01(fv);
        fw = clamp01(fw);
        double acc = 0;
        for (int dc = 0; dc < 2; dc++) {
            for (int dv = 0; dv < 2; dv++) {
                for (int dw = 0; dw < 2; dw++) {
                    double w = (dc == 1 ? fc : 1 - fc) * (dv == 1 ? fv : 1 - fv) * (dw == 1 ? fw : 1 - fw);
                    int idx = ((ci + dc) * VALUE_NODES.length + (vi + dv)) * HUE_NODES + (wi + dw);
                    acc += w * LIGHT_ALPHA[idx];
                }
            }
        }
        return acc;
    }

    private static double clamp01(double v) {
        return v < 0 ? 0 : (v > 1 ? 1 : v);
    }

    /// Applies a 12-float colour matrix to one 0xRRGGBB colour (clamped), the
    /// per-pixel operation of Graphics.colorMatrixRegion at full coverage.
    ///
    /// #### Parameters
    ///
    /// - `m`: the matrix, as returned by `#forTint(int, boolean)`
    ///
    /// - `rgb`: the colour, 0xRRGGBB
    ///
    /// #### Returns
    ///
    /// the transformed colour, 0xRRGGBB
    public static int apply(float[] m, int rgb) {
        float r = ((rgb >> 16) & 0xff) / 255f;
        float g = ((rgb >> 8) & 0xff) / 255f;
        float b = (rgb & 0xff) / 255f;
        int out = 0;
        for (int row = 0; row < 3; row++) {
            float v = m[row * 4] * r + m[row * 4 + 1] * g + m[row * 4 + 2] * b + m[row * 4 + 3];
            int iv = Math.round((v < 0 ? 0 : (v > 1 ? 1 : v)) * 255);
            out = (out << 8) | iv;
        }
        return out;
    }
